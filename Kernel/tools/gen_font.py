#!/usr/bin/env python3
"""Emit an 8x16 ASCII font as C for the kernel console."""
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "src" / "kfont.c"

try:
    from PIL import Image, ImageDraw, ImageFont
except ImportError:
    Image = None


def raster_pil() -> list[list[int]]:
    fonts = [
        r"C:\Windows\Fonts\consola.ttf",
        r"C:\Windows\Fonts\cour.ttf",
        r"C:\Windows\Fonts\lucon.ttf",
        "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf",
    ]
    font = None
    for p in fonts:
        try:
            font = ImageFont.truetype(p, 13)
            break
        except OSError:
            continue
    if font is None:
        font = ImageFont.load_default()
    glyphs = []
    for cp in range(256):
        im = Image.new("L", (8, 16), 0)
        dr = ImageDraw.Draw(im)
        ch = chr(cp) if 32 <= cp < 127 else " "
        dr.text((0, 0), ch, font=font, fill=255)
        rows = []
        pix = im.load()
        for y in range(16):
            bits = 0
            for x in range(8):
                if pix[x, y] > 80:
                    bits |= 0x80 >> x
            rows.append(bits)
        glyphs.append(rows)
    return glyphs


