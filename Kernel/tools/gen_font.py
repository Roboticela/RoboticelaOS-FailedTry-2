def main() -> None:
    glyphs = raster_pil() if Image else raster_blocky()
    lines = [
        "/* Generated 8x16 glyphs for the kernel console. */",
        "#include <stdint.h>",
        "",
        "const uint8_t kfont8x16[256][16] = {",
    ]
    for rows in glyphs:
        body = ", ".join(f"0x{b:02x}" for b in rows)
        lines.append(f"    {{{body}}},")
    lines.append("};")
    lines.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="ascii")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
