#!/usr/bin/env python3
"""
Roboticela Unicode data pipeline orchestrator (Goal 3.14).

Usage:
  python generate_all.py                  # validate sources + generate all tables
  python generate_all.py --verify-only    # checksum + version checks only
  python generate_all.py --repro          # generate twice into temp dirs and diff
  python generate_all.py --update-golden  # after successful generate, refresh golden_hashes.json
  python generate_all.py --check-golden   # compare generated artifacts to golden hashes

Normal runtime builds do NOT run this. Regeneration is an explicit developer step.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

from robo_unicode_version import EMOJI_UCD_RELATION, EMOJI_VERSION, GENERATOR_VERSION, UCD_VERSION, assert_versions_coherent
from ucd_common import (
    HERE,
    collect_generated_paths,
    hash_generated,
    load_golden,
    load_manifest,
    sync_c_version_header,
    verify_sources,
    write_json,
    GOLDEN_PATH,
)


def run_script(name: str) -> None:
    script = HERE / name
    print(f"==> {name}")
    r = subprocess.run([sys.executable, str(script)], cwd=str(HERE))
    if r.returncode != 0:
        raise SystemExit(f"{name} failed with exit {r.returncode}")


def generate_all() -> None:
    manifest = load_manifest()
    for line in verify_sources(manifest):
        print(line)
    sync_c_version_header()
    print(f"OK synced RoboUnicodeVersion.h ({UCD_VERSION} / Emoji {EMOJI_VERSION})")

    for g in manifest["generators"]:
        run_script(g)
    for v in manifest.get("validators") or []:
        run_script(v)

    print(f"OK all generators complete (generator {GENERATOR_VERSION})")
    print(EMOJI_UCD_RELATION)


def update_golden() -> None:
    manifest = load_manifest()
    paths = collect_generated_paths(manifest)
    # Version header is always regenerated by sync
    sync_c_version_header()
    hashes = hash_generated(paths)
    payload = {
        "unicode_version": UCD_VERSION,
        "emoji_version": EMOJI_VERSION,
        "generator_version": GENERATOR_VERSION,
        "artifacts": hashes,
    }
    write_json(GOLDEN_PATH, payload)
    print(f"Wrote {GOLDEN_PATH} ({len(hashes)} artifacts)")


def check_golden() -> None:
    golden = load_golden()
    if golden is None:
        raise SystemExit(f"missing {GOLDEN_PATH} — run with --update-golden first")
    if golden.get("unicode_version") != UCD_VERSION:
        raise SystemExit("golden unicode_version mismatch vs pin")
    if golden.get("emoji_version") != EMOJI_VERSION:
        raise SystemExit("golden emoji_version mismatch vs pin")
    manifest = load_manifest()
    actual = hash_generated(collect_generated_paths(manifest))
    expected = golden.get("artifacts") or {}
    failed = 0
    for rel, digest in sorted(expected.items()):
        got = actual.get(rel)
        if got is None:
            print(f"FAIL missing artifact {rel}")
            failed += 1
        elif got != digest:
            print(f"FAIL hash drift {rel}")
            print(f"  expected {digest}")
            print(f"  actual   {got}")
            failed += 1
        else:
            print(f"PASS {rel}")
    for rel in actual:
        if rel not in expected:
            print(f"FAIL unexpected new artifact {rel} (update golden)")
            failed += 1
    if failed:
        raise SystemExit(f"{failed} golden hash failure(s)")
    print(f"OK golden hashes ({len(expected)} artifacts)")


def repro_check() -> None:
    """Generate twice into isolated output trees and compare."""
    manifest = load_manifest()
    for line in verify_sources(manifest):
        print(line)

    # Snapshot current generated files, generate into temp by temporarily
    # copying generators' outputs via two full runs with file copies.
    # Approach: run generate_all, snapshot hashes; run again; compare hashes.
    print("==> repro pass 1")
    generate_all()
    h1 = hash_generated(collect_generated_paths(manifest))

    print("==> repro pass 2")
    generate_all()
    h2 = hash_generated(collect_generated_paths(manifest))

    diffs = [k for k in h1 if h1[k] != h2.get(k)]
    extras = [k for k in h2 if k not in h1]
    if diffs or extras:
        for k in diffs:
            print(f"FAIL nondeterministic {k}")
            print(f"  pass1 {h1[k]}")
            print(f"  pass2 {h2.get(k)}")
        for k in extras:
            print(f"FAIL extra {k}")
        raise SystemExit("reproducibility check FAILED")
    print(f"OK deterministic generation ({len(h1)} artifacts identical across two runs)")


def main() -> int:
    assert_versions_coherent()
    ap = argparse.ArgumentParser(description="Roboticela Unicode data pipeline")
    ap.add_argument("--verify-only", action="store_true")
    ap.add_argument("--repro", action="store_true")
    ap.add_argument("--update-golden", action="store_true")
    ap.add_argument("--check-golden", action="store_true")
    args = ap.parse_args()

    print(f"Unicode {UCD_VERSION} | Emoji {EMOJI_VERSION} | generator {GENERATOR_VERSION}")

    if args.verify_only:
        manifest = load_manifest()
        for line in verify_sources(manifest):
            print(line)
        sync_c_version_header()
        print("OK verify-only")
        return 0

    if args.repro:
        repro_check()
        return 0

    if args.check_golden:
        check_golden()
        return 0

    generate_all()

    if args.update_golden:
        update_golden()

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
