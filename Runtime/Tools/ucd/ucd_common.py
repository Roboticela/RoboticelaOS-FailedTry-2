#!/usr/bin/env python3
"""
Shared Unicode data-pipeline helpers (Goal 3.14).

Used by generate_all.py, verify_pipeline.py, and individual generators.
"""

from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path
from typing import Any

from robo_unicode_version import (
    EMOJI_VERSION,
    GENERATOR_VERSION,
    UCD_VERSION,
)

HERE = Path(__file__).resolve().parent  # runtime/Tools/ucd
RUNTIME = HERE.parent.parent  # runtime/
SRC = HERE / "source"
MANIFEST_PATH = HERE / "manifest.json"
GOLDEN_PATH = HERE / "golden_hashes.json"

MAX_CP = 0x10FFFF
SURROGATE_LO = 0xD800
SURROGATE_HI = 0xDFFF

VERSION_IN_NAME = re.compile(r"-(\d+\.\d+(?:\.\d+)?)\.txt\s*$", re.IGNORECASE)
VERSION_LINE = re.compile(
    r"^#\s*(?:Version|Emoji Version)\s*:\s*(\d+\.\d+(?:\.\d+)?)\b",
    re.IGNORECASE,
)
FILENAME_VERSION = re.compile(r"#\s*[\w.-]+-(\d+\.\d+(?:\.\d+)?)\.txt\b")


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def load_manifest() -> dict[str, Any]:
    if not MANIFEST_PATH.is_file():
        raise SystemExit(f"missing manifest: {MANIFEST_PATH}")
    data = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    if data.get("unicode_version") != UCD_VERSION:
        raise SystemExit(
            f"manifest unicode_version={data.get('unicode_version')!r} "
            f"!= pin {UCD_VERSION!r} (robo_unicode_version.py)"
        )
    if data.get("emoji_version") != EMOJI_VERSION:
        raise SystemExit(
            f"manifest emoji_version={data.get('emoji_version')!r} "
            f"!= pin {EMOJI_VERSION!r}"
        )
    return data


def load_golden() -> dict[str, Any] | None:
    if not GOLDEN_PATH.is_file():
        return None
    return json.loads(GOLDEN_PATH.read_text(encoding="utf-8"))


def write_json(path: Path, obj: Any) -> None:
    path.write_text(json.dumps(obj, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def extract_source_version_hints(path: Path) -> list[str]:
    """Return version strings found in the first ~40 comment lines."""
    found: list[str] = []
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError as e:
        raise SystemExit(f"cannot read {path}: {e}") from e
    for i, line in enumerate(text.splitlines()):
        if i > 40:
            break
        if not line.startswith("#"):
            if i > 5 and line.strip() and not line.startswith("#"):
                # UnicodeData has no header — stop early once data starts
                if path.name == "UnicodeData.txt":
                    break
            continue
        m = VERSION_LINE.match(line) or FILENAME_VERSION.search(line)
        if m:
            found.append(m.group(1))
    return found


def versions_compatible(hint: str, expected_ucd: str, expected_emoji: str) -> bool:
    """Accept UCD x.y.z or emoji x.y matching pins."""
    if hint == expected_ucd:
        return True
    if hint == expected_emoji:
        return True
    # "16.0" may appear for UCD files that omit patch
    if hint == ".".join(expected_ucd.split(".")[:2]) and expected_ucd.endswith(".0"):
        return True
    return False


def validate_codepoint(cp: int, *, allow_surrogate: bool = False) -> None:
    if cp < 0 or cp > MAX_CP:
        raise ValueError(f"code point out of range: {cp:#x}")
    if not allow_surrogate and SURROGATE_LO <= cp <= SURROGATE_HI:
        raise ValueError(f"surrogate code point not allowed: {cp:#x}")


def validate_range(lo: int, hi: int, *, allow_surrogate: bool = False) -> None:
    validate_codepoint(lo, allow_surrogate=allow_surrogate)
    validate_codepoint(hi, allow_surrogate=allow_surrogate)
    if lo > hi:
        raise ValueError(f"inverted range {lo:#x}..{hi:#x}")


def check_non_overlapping_ranges(ranges: list[tuple[int, int]], label: str) -> None:
    ordered = sorted(ranges, key=lambda r: r[0])
    prev_hi = -1
    for lo, hi in ordered:
        if lo <= prev_hi:
            raise SystemExit(f"{label}: overlapping ranges near {lo:#x}..{hi:#x}")
        prev_hi = hi


def generated_banner(tool: str, *, extra: str = "") -> list[str]:
    """Deterministic header lines for generated artifacts (no wall-clock time)."""
    lines = [
        f"/* Auto-generated by Tools/ucd/{tool} — DO NOT EDIT. */",
        f"/* Roboticela generator {GENERATOR_VERSION} | Unicode {UCD_VERSION}"
        f" | Emoji {EMOJI_VERSION} */",
    ]
    if extra:
        lines.append(f"/* {extra} */")
    return lines


def verify_sources(manifest: dict[str, Any], *, require_present: bool = True) -> list[str]:
    """
    Verify source files against manifest checksums and version hints.
    Returns list of human-readable OK lines; raises SystemExit on failure.
    """
    msgs: list[str] = []
    files = manifest.get("files") or []
    if not files:
        raise SystemExit("manifest has no files[]")

    for entry in files:
        name = entry["name"]
        path = SRC / name
        role = entry.get("role", "unknown")
        required = bool(entry.get("required", True))
        if not path.is_file():
            if required and require_present:
                raise SystemExit(f"missing required source: {path}")
            msgs.append(f"SKIP missing optional {name}")
            continue

        digest = sha256_file(path)
        expected = entry.get("sha256", "").lower()
        if expected and digest != expected.lower():
            raise SystemExit(
                f"checksum mismatch for {name}:\n"
                f"  expected {expected}\n"
                f"  actual   {digest}"
            )
        msgs.append(f"OK sha256 {name} ({role})")

        # Version metadata where files carry it
        if entry.get("check_version_header", True) and name != "UnicodeData.txt":
            hints = extract_source_version_hints(path)
            if hints:
                if not any(
                    versions_compatible(h, UCD_VERSION, EMOJI_VERSION) for h in hints
                ):
                    raise SystemExit(
                        f"version mismatch in {name}: found {hints}, "
                        f"expected Unicode {UCD_VERSION} / Emoji {EMOJI_VERSION}"
                    )
                msgs.append(f"OK version {name}: {hints[0]}")
    return msgs


def collect_generated_paths(manifest: dict[str, Any]) -> list[Path]:
    outs: list[Path] = []
    for rel in manifest.get("generated_outputs") or []:
        outs.append(RUNTIME / rel.replace("\\", "/"))
    return outs


def hash_generated(paths: list[Path]) -> dict[str, str]:
    out: dict[str, str] = {}
    for p in paths:
        if not p.is_file():
            raise SystemExit(f"missing generated artifact: {p}")
        rel = p.relative_to(RUNTIME).as_posix()
        out[rel] = sha256_file(p)
    return out


def sync_c_version_header() -> Path:
    """Write Include/RoboUnicode/RoboUnicodeVersion.h from the Python pin."""
    from robo_unicode_version import (
        EMOJI_VERSION_MAJOR,
        EMOJI_VERSION_MINOR,
        UCD_VERSION_MAJOR,
        UCD_VERSION_MINOR,
        UCD_VERSION_PATCH,
    )

    out = RUNTIME / "Include" / "RoboUnicode" / "RoboUnicodeVersion.h"
    body = "\n".join(
        [
            "/* Auto-synced by Tools/ucd — single Unicode version pin (Goal 3.14). */",
            "/* Source of truth for generators: Tools/ucd/robo_unicode_version.py */",
            "#ifndef ROBO_UNICODE_VERSION_H",
            "#define ROBO_UNICODE_VERSION_H",
            "",
            f"#define ROBO_UNICODE_VERSION_MAJOR {UCD_VERSION_MAJOR}",
            f"#define ROBO_UNICODE_VERSION_MINOR {UCD_VERSION_MINOR}",
            f"#define ROBO_UNICODE_VERSION_PATCH {UCD_VERSION_PATCH}",
            f'#define ROBO_UNICODE_VERSION_STRING "{UCD_VERSION}"',
            "",
            f"#define ROBO_EMOJI_VERSION_MAJOR {EMOJI_VERSION_MAJOR}",
            f"#define ROBO_EMOJI_VERSION_MINOR {EMOJI_VERSION_MINOR}",
            f'#define ROBO_EMOJI_VERSION_STRING "{EMOJI_VERSION}"',
            "",
            f'#define ROBO_UNICODE_GENERATOR_VERSION "{GENERATOR_VERSION}"',
            "",
            "#endif /* ROBO_UNICODE_VERSION_H */",
            "",
        ]
    )
    out.parent.mkdir(parents=True, exist_ok=True)
    if out.is_file() and out.read_text(encoding="utf-8") == body:
        return out
    out.write_text(body, encoding="utf-8")
    return out


def die(msg: str) -> None:
    print(msg, file=sys.stderr)
    raise SystemExit(1)
