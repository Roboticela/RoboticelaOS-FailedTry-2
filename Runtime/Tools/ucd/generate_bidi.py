#!/usr/bin/env python3
"""
Generate Unicode Bidi_Class + bracket tables (UAX #9) for UCD 16.0.0.

Inputs:
  Tools/ucd/source/DerivedBidiClass.txt
  Tools/ucd/source/BidiBrackets.txt
  Tools/ucd/source/BidiCharacterTest.txt (optional conformance .inc)

Outputs:
  Include/RoboUnicode/RoboBidiData.h
  Source/RoboUnicode/data/robo_bidi_data.c
  Tests/Data/robo_bidi_character_conformance.bin  (packed BidiCharacterTest)
  Tests/Data/robo_bidi_character_conformance.h
"""

from __future__ import annotations

import sys
from pathlib import Path

from robo_unicode_version import UCD_VERSION

ROOT = Path(__file__).resolve().parents[2]
SRC = Path(__file__).resolve().parent / "source"
OUT_H = ROOT / "Include" / "RoboUnicode" / "RoboBidiData.h"
OUT_C = ROOT / "Source" / "RoboUnicode" / "data" / "robo_bidi_data.c"
OUT_TEST_BIN = ROOT / "Tests" / "Data" / "robo_bidi_character_conformance.bin"
OUT_TEST_META = ROOT / "Tests" / "Data" / "robo_bidi_character_conformance.h"

MAX_CP = 0x110000

# Enum order for C
BC_ORDER = [
    "L",
    "R",
    "AL",
    "EN",
    "ES",
    "ET",
    "AN",
    "CS",
    "NSM",
    "BN",
    "B",
    "S",
    "WS",
    "ON",
    "LRE",
    "LRO",
    "RLE",
    "RLO",
    "PDF",
    "LRI",
    "RLI",
    "FSI",
    "PDI",
]

LONG_TO_SHORT = {
    "Left_To_Right": "L",
    "Right_To_Left": "R",
    "Arabic_Letter": "AL",
    "European_Number": "EN",
    "European_Separator": "ES",
    "European_Terminator": "ET",
    "Arabic_Number": "AN",
    "Common_Separator": "CS",
    "Nonspacing_Mark": "NSM",
    "Boundary_Neutral": "BN",
    "Paragraph_Separator": "B",
    "Segment_Separator": "S",
    "White_Space": "WS",
    "Whitespace": "WS",
    "Other_Neutral": "ON",
    "Left_To_Right_Embedding": "LRE",
    "Left_To_Right_Override": "LRO",
    "Right_To_Left_Embedding": "RLE",
    "Right_To_Left_Override": "RLO",
    "Pop_Directional_Format": "PDF",
    "Left_To_Right_Isolate": "LRI",
    "Right_To_Left_Isolate": "RLI",
    "First_Strong_Isolate": "FSI",
    "Pop_Directional_Isolate": "PDI",
}


def parse_cp(tok: str) -> int:
    return int(tok.strip(), 16)


def parse_range(field: str) -> tuple[int, int]:
    field = field.strip()
    if ".." in field:
        a, b = field.split("..")
        return parse_cp(a), parse_cp(b)
    cp = parse_cp(field)
    return cp, cp


def normalize_bc(name: str) -> str:
    name = name.strip()
    return LONG_TO_SHORT.get(name, name)


def compress_ranges(arr, default):
    ranges = []
    i = 0
    while i < MAX_CP:
        v = arr[i]
        j = i + 1
        while j < MAX_CP and arr[j] == v:
            j += 1
        if v != default:
            ranges.append((i, j - 1, v))
        i = j
    return ranges


def main() -> int:
    path = SRC / "DerivedBidiClass.txt"
    if not path.exists():
        print("Missing DerivedBidiClass.txt", file=sys.stderr)
        return 1

    bc_map = {name: i for i, name in enumerate(BC_ORDER)}
    # Default L (0)
    arr = [0] * MAX_CP

    with path.open("r", encoding="utf-8") as f:
        for line in f:
            raw = line.strip()
            if raw.startswith("@missing:"):
                # @missing: 0000..10FFFF; Left_To_Right
                continue
            line = raw.split("#", 1)[0].strip()
            if not line or ";" not in line:
                continue
            left, rest = line.split(";", 1)
            val = normalize_bc(rest.split("#", 1)[0].strip())
            if val not in bc_map:
                print(f"Unknown Bidi_Class: {val}", file=sys.stderr)
                return 1
            start, end = parse_range(left)
            for cp in range(start, end + 1):
                if 0 <= cp < MAX_CP:
                    arr[cp] = bc_map[val]

    ranges = compress_ranges(arr, 0)

    # Brackets
    brackets: list[tuple[int, int, str]] = []
    bpath = SRC / "BidiBrackets.txt"
    if bpath.exists():
        with bpath.open("r", encoding="utf-8") as f:
            for line in f:
                line = line.split("#", 1)[0].strip()
                if not line or ";" not in line:
                    continue
                parts = [p.strip() for p in line.split(";")]
                if len(parts) < 3:
                    continue
                cp = parse_cp(parts[0])
                pair = parse_cp(parts[1])
                typ = parts[2]  # o or c
                brackets.append((cp, pair, typ))

    OUT_H.parent.mkdir(parents=True, exist_ok=True)
    OUT_C.parent.mkdir(parents=True, exist_ok=True)

    h = [
        "/* Auto-generated by Tools/ucd/generate_bidi.py — DO NOT EDIT. */",
        f"/* Unicode UCD version: {UCD_VERSION} — Bidirectional Algorithm (UAX #9) */",
        "#ifndef ROBO_BIDI_DATA_H",
        "#define ROBO_BIDI_DATA_H",
        "",
        '#include "RoboUnicode/RoboUnicode.h"',
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
        "",
        f'#define ROBO_BIDI_UCD_VERSION "{UCD_VERSION}"',
        "",
        "typedef enum robo_unicode_bidi_class {",
    ]
    for i, name in enumerate(BC_ORDER):
        h.append(f"    ROBO_U_BC_{name} = {i},")
    h.append("    ROBO_U_BC_COUNT")
    h.append("} robo_unicode_bidi_class_t;")
    h.append("")
    h.append("typedef struct robo_bidi_range8 {")
    h.append("    uint32_t start;")
    h.append("    uint32_t end;")
    h.append("    uint8_t value;")
    h.append("} robo_bidi_range8_t;")
    h.append("")
    h.append("typedef struct robo_bidi_bracket {")
    h.append("    uint32_t cp;")
    h.append("    uint32_t pair;")
    h.append("    uint8_t is_open; /* 1=open, 0=close */")
    h.append("} robo_bidi_bracket_t;")
    h.append("")
    h.append("robo_unicode_bidi_class_t robo_bidi_class_property(robo_uchar32_t cp);")
    h.append("int robo_bidi_bracket_lookup(robo_uchar32_t cp, uint32_t *pair_out, int *is_open_out);")
    h.append("")
    h.append("#ifdef __cplusplus")
    h.append("}")
    h.append("#endif")
    h.append("")
    h.append("#endif")
    OUT_H.write_text("\n".join(h) + "\n", encoding="utf-8")

    c = [
        "/* Auto-generated by Tools/ucd/generate_bidi.py — DO NOT EDIT. */",
        f"/* Unicode UCD {UCD_VERSION} */",
        '#include "RoboUnicode/RoboBidiData.h"',
        "",
        "static const robo_bidi_range8_t robo_bidi_bc_ranges[] = {",
    ]
    for start, end, val in ranges:
        c.append(f"    {{ 0x{start:04X}u, 0x{end:04X}u, {val}u }},")
    if not ranges:
        c.append("    { 0, 0, 0 },")
    c.append("};")
    c.append(f"static const size_t robo_bidi_bc_ranges_count = {len(ranges)};")
    c.append("")
    c.append("static const robo_bidi_bracket_t robo_bidi_brackets[] = {")
    for cp, pair, typ in brackets:
        is_open = 1 if typ == "o" else 0
        c.append(f"    {{ 0x{cp:04X}u, 0x{pair:04X}u, {is_open}u }},")
    if not brackets:
        c.append("    { 0, 0, 0 },")
    c.append("};")
    c.append(f"static const size_t robo_bidi_brackets_count = {len(brackets)};")
    c.append(
        r"""
robo_unicode_bidi_class_t robo_bidi_class_property(robo_uchar32_t cp)
{
    size_t lo = 0, hi = robo_bidi_bc_ranges_count;
    while (lo < hi) {
        size_t mid = lo + (hi - lo) / 2u;
        const robo_bidi_range8_t *r = &robo_bidi_bc_ranges[mid];
        if (cp < r->start) {
            hi = mid;
        } else if (cp > r->end) {
            lo = mid + 1u;
        } else {
            return (robo_unicode_bidi_class_t)r->value;
        }
    }
    return ROBO_U_BC_L;
}

int robo_bidi_bracket_lookup(robo_uchar32_t cp, uint32_t *pair_out, int *is_open_out)
{
    size_t lo = 0, hi = robo_bidi_brackets_count;
    while (lo < hi) {
        size_t mid = lo + (hi - lo) / 2u;
        const robo_bidi_bracket_t *b = &robo_bidi_brackets[mid];
        if (cp < b->cp) {
            hi = mid;
        } else if (cp > b->cp) {
            lo = mid + 1u;
        } else {
            if (pair_out) {
                *pair_out = b->pair;
            }
            if (is_open_out) {
                *is_open_out = (int)b->is_open;
            }
            return 1;
        }
    }
    return 0;
}
"""
    )
    OUT_C.write_text("\n".join(c) + "\n", encoding="utf-8")
    print(f"Wrote {OUT_H} / {OUT_C} (bc_ranges={len(ranges)}, brackets={len(brackets)})")

    # Binary character conformance (avoids multi-10MB C text compile cost)
    #
    # Layout (little-endian):
    #   magic u32 'BIDI' (0x49444942)
    #   ucd_major, ucd_minor, ucd_patch, reserved  (4 x u16)
    #   case_count u32
    #   For each case:
    #     cp_count u16, reorder_count u16, para_dir u8, para_level u8, pad u16
    #     cps[cp_count] as u32
    #     levels[cp_count] as u8  (255 = X9-removed 'x')
    #     pad to 2-byte alignment if cp_count odd
    #     reorder[reorder_count] as u16
    tpath = SRC / "BidiCharacterTest.txt"
    if tpath.exists():
        import struct

        cases = []
        for raw in tpath.read_text(encoding="utf-8").splitlines():
            line = raw.split("#", 1)[0].strip()
            if not line:
                continue
            parts = line.split(";")
            if len(parts) < 5:
                continue
            cps = [parse_cp(x) for x in parts[0].split()]
            para_dir = int(parts[1].strip())
            para_level = int(parts[2].strip())
            levels = []
            for tok in parts[3].split():
                if tok == "x":
                    levels.append(255)
                else:
                    levels.append(int(tok))
            reorder = [int(x) for x in parts[4].split()]
            cases.append((cps, para_dir, para_level, levels, reorder))

        buf = bytearray()
        buf += struct.pack("<I", 0x49444942)
        maj, minor, patch = (int(x) for x in UCD_VERSION.split("."))
        buf += struct.pack("<HHHH", maj, minor, patch, 0)
        buf += struct.pack("<I", len(cases))
        for cps, para_dir, para_level, levels, reorder in cases:
            n = len(cps)
            rn = len(reorder)
            buf += struct.pack("<HHBBH", n, rn, para_dir, para_level, 0)
            for cp in cps:
                buf += struct.pack("<I", cp)
            buf += bytes(levels)
            if n % 2 == 1:
                buf += b"\x00"
            for idx in reorder:
                buf += struct.pack("<H", idx)

        OUT_TEST_BIN.parent.mkdir(parents=True, exist_ok=True)
        OUT_TEST_BIN.write_bytes(bytes(buf))
        OUT_TEST_META.write_text(
            "/* Auto-generated — BidiCharacterTest binary fixture metadata. */\n"
            f"/* Unicode {UCD_VERSION}, {len(cases)} cases */\n"
            "#ifndef ROBO_BIDI_CHARACTER_CONFORMANCE_H\n"
            "#define ROBO_BIDI_CHARACTER_CONFORMANCE_H\n"
            f"#define ROBO_BIDI_CHAR_CONF_CASE_COUNT {len(cases)}u\n"
            "#define ROBO_BIDI_CHAR_CONF_MAGIC 0x49444942u\n"
            "#endif\n",
            encoding="utf-8",
        )
        # Remove legacy bulky .inc if present
        legacy = OUT_TEST_BIN.with_suffix(".inc")
        if legacy.exists():
            legacy.unlink()
        print(f"Wrote {OUT_TEST_BIN} ({len(cases)} cases, {len(buf)} bytes)")
        print(f"Wrote {OUT_TEST_META}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
