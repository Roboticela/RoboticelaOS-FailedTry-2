#!/usr/bin/env python3
"""
Generate Unicode Word Boundary tables (UAX #29) for UCD 16.0.0.

Inputs:
  Tools/ucd/source/WordBreakProperty.txt
  Tools/ucd/source/WordBreakTest.txt

Outputs:
  Include/RoboUnicode/RoboWordData.h
  Source/RoboUnicode/data/robo_word_data.c
  Tests/Data/robo_word_conformance.inc
"""

from __future__ import annotations

import sys
from pathlib import Path

from robo_unicode_version import UCD_VERSION

ROOT = Path(__file__).resolve().parents[2]
SRC = Path(__file__).resolve().parent / "source"
OUT_H = ROOT / "Include" / "RoboUnicode" / "RoboWordData.h"
OUT_C = ROOT / "Source" / "RoboUnicode" / "data" / "robo_word_data.c"
OUT_TEST = ROOT / "Tests" / "Data" / "robo_word_conformance.inc"

MAX_CP = 0x110000

WB_ORDER = [
    "Other",
    "CR",
    "LF",
    "Newline",
    "Extend",
    "ZWJ",
    "Regional_Indicator",
    "Format",
    "Katakana",
    "Hebrew_Letter",
    "ALetter",
    "Single_Quote",
    "Double_Quote",
    "MidNumLet",
    "MidLetter",
    "MidNum",
    "Numeric",
    "ExtendNumLet",
    "WSegSpace",
]


def parse_cp(tok: str) -> int:
    return int(tok.strip(), 16)


def load_lines(path: Path):
    with path.open("r", encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if line:
                yield line


def parse_range(field: str) -> tuple[int, int]:
    field = field.strip()
    if ".." in field:
        a, b = field.split("..")
        return parse_cp(a), parse_cp(b)
    cp = parse_cp(field)
    return cp, cp


def compress_ranges(arr, default):
    ranges = []
    i = 0
    while i < MAX_CP:
        v = arr[i]
        j = i + 1
        while j < MAX_CP and arr[j] == v:
            j += 1
        if v != default:
            ranges.append((i, j - 1, v))
        i = j
    return ranges


def main() -> int:
    wb_path = SRC / "WordBreakProperty.txt"
    if not wb_path.exists():
        print("Missing WordBreakProperty.txt", file=sys.stderr)
        return 1

    wb_arr = [0] * MAX_CP
    wb_map = {name: i for i, name in enumerate(WB_ORDER)}

    for line in load_lines(wb_path):
        if ";" not in line:
            continue
        left, rest = line.split(";", 1)
        val = rest.split("#", 1)[0].strip()
        if val not in wb_map:
            print(f"Unknown WB value: {val}", file=sys.stderr)
            return 1
        start, end = parse_range(left)
        for cp in range(start, end + 1):
            if 0 <= cp < MAX_CP:
                wb_arr[cp] = wb_map[val]

    ranges = compress_ranges(wb_arr, 0)

    OUT_H.parent.mkdir(parents=True, exist_ok=True)
    OUT_C.parent.mkdir(parents=True, exist_ok=True)

    h = [
        "/* Auto-generated by Tools/ucd/generate_word.py — DO NOT EDIT. */",
        f"/* Unicode UCD version: {UCD_VERSION} — Word Boundaries (UAX #29) */",
        "#ifndef ROBO_WORD_DATA_H",
        "#define ROBO_WORD_DATA_H",
        "",
        '#include "RoboUnicode/RoboUnicode.h"',
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
        "",
        f'#define ROBO_WORD_UCD_VERSION "{UCD_VERSION}"',
        "",
        "typedef enum robo_unicode_word_break {",
    ]
    for i, name in enumerate(WB_ORDER):
        suffix = name.upper()
        if name == "Other":
            h.append(f"    ROBO_U_WB_OTHER = {i},")
        else:
            h.append(f"    ROBO_U_WB_{suffix} = {i},")
    h.append("    ROBO_U_WB_COUNT")
    h.append("} robo_unicode_word_break_t;")
    h.append("")
    h.append("typedef struct robo_word_range8 {")
    h.append("    uint32_t start;")
    h.append("    uint32_t end;")
    h.append("    uint8_t value;")
    h.append("} robo_word_range8_t;")
    h.append("")
    h.append("robo_unicode_word_break_t robo_word_break_property(Uchar32 cp);")
    h.append("")
    h.append("#ifdef __cplusplus")
    h.append("}")
    h.append("#endif")
    h.append("")
    h.append("#endif")
    OUT_H.write_text("\n".join(h) + "\n", encoding="utf-8")

    c = [
        "/* Auto-generated by Tools/ucd/generate_word.py — DO NOT EDIT. */",
        f"/* Unicode UCD {UCD_VERSION} */",
        '#include "RoboUnicode/RoboWordData.h"',
        "",
        "static const robo_word_range8_t robo_word_wb_ranges[] = {",
    ]
    for start, end, val in ranges:
        c.append(f"    {{ 0x{start:04X}u, 0x{end:04X}u, {val}u }},")
    if not ranges:
        c.append("    { 0, 0, 0 },")
    c.append("};")
    c.append(f"static const size_t robo_word_wb_ranges_count = {len(ranges)};")
    c.append(
        r"""
robo_unicode_word_break_t robo_word_break_property(Uchar32 cp)
{
    size_t lo = 0, hi = robo_word_wb_ranges_count;
    while (lo < hi) {
        size_t mid = lo + (hi - lo) / 2u;
        const robo_word_range8_t *r = &robo_word_wb_ranges[mid];
        if (cp < r->start) {
            hi = mid;
        } else if (cp > r->end) {
            lo = mid + 1u;
        } else {
            return (robo_unicode_word_break_t)r->value;
        }
    }
    return ROBO_U_WB_OTHER;
}
"""
    )
    OUT_C.write_text("\n".join(c) + "\n", encoding="utf-8")
    print(f"Wrote {OUT_H} / {OUT_C} (ranges={len(ranges)})")

    test_path = SRC / "WordBreakTest.txt"
    if test_path.exists():
        cases = []
        for raw in test_path.read_text(encoding="utf-8").splitlines():
            line = raw.split("#", 1)[0].strip()
            if not line or line.startswith("@"):
                continue
            tokens = line.split()
            cps = []
            breaks = []
            pending = None
            for tok in tokens:
                if tok == "÷":
                    pending = 1
                elif tok == "×":
                    pending = 0
                else:
                    if pending is None:
                        pending = 1
                    breaks.append(pending)
                    cps.append(parse_cp(tok))
                    pending = None
            if cps:
                cases.append((cps, breaks))

        lines = [
            "/* Auto-generated from WordBreakTest.txt — DO NOT EDIT. */",
            f"/* Unicode {UCD_VERSION}, {len(cases)} cases */",
            "typedef struct robo_word_conf_case {",
            "    const Uchar32 *cps;",
            "    const unsigned char *breaks;",
            "    unsigned cp_count;",
            "} robo_word_conf_case_t;",
            "",
        ]
        cp_pool: list[int] = []
        br_pool: list[int] = []
        for cps, brs in cases:
            cp_pool.extend(cps)
            cp_pool.append(0xFFFFFFFF)
            br_pool.extend(brs)
            br_pool.append(255)

        lines.append("static const Uchar32 robo_word_conf_cps[] = {")
        for i in range(0, len(cp_pool), 8):
            chunk = cp_pool[i : i + 8]
            lines.append("    " + ", ".join(f"0x{x:08X}u" for x in chunk) + ",")
        lines.append("};")
        lines.append("static const unsigned char robo_word_conf_breaks[] = {")
        for i in range(0, len(br_pool), 16):
            chunk = br_pool[i : i + 16]
            lines.append("    " + ", ".join(str(x) for x in chunk) + ",")
        lines.append("};")
        lines.append("static const robo_word_conf_case_t robo_word_conf_cases[] = {")
        cp_i = 0
        br_i = 0
        for cps, brs in cases:
            n = len(cps)
            lines.append(
                f"    {{ robo_word_conf_cps + {cp_i}, robo_word_conf_breaks + {br_i}, {n}u }},"
            )
            cp_i += n + 1
            br_i += n + 1
        lines.append("};")
        lines.append(f"static const size_t robo_word_conf_cases_count = {len(cases)};")
        OUT_TEST.parent.mkdir(parents=True, exist_ok=True)
        OUT_TEST.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"Wrote {OUT_TEST} ({len(cases)} cases)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
