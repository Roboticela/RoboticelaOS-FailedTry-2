#!/usr/bin/env python3
"""
Emit RoboI18N relative-time tables from CLDR dateFields.json (Goals 4.7 / 4.19).

Inputs: Tools/i18n/source/cldr-46.0.0/dates/*/dateFields.json
Outputs:
  Include/RoboI18N/RoboRelData.h
  Source/RoboI18N/data/robo_rel_data.c
  Tools/i18n/relative_golden_hashes.json
"""

from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path

from robo_i18n_version import (
    CLDR_JSON_PACKAGE,
    CLDR_UNICODE_VERSION,
    CLDR_VERSION,
    GENERATOR_VERSION,
)

HERE = Path(__file__).resolve().parent
RUNTIME = HERE.parent.parent
SRC = HERE / "source" / f"cldr-{CLDR_JSON_PACKAGE}" / "dates"
OUT_H = RUNTIME / "Include" / "RoboI18N" / "RoboRelData.h"
OUT_C = RUNTIME / "Source" / "RoboI18N" / "data" / "robo_rel_data.c"
GOLDEN = HERE / "relative_golden_hashes.json"

# Unit id order matches robo_i18n_relative_unit_t
UNITS = ("year", "quarter", "month", "week", "day", "hour", "minute", "second")
WIDTHS = ("long", "short", "narrow")  # long = bare field name
PLURAL_CATS = ("zero", "one", "two", "few", "many", "other")


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    h.update(path.read_bytes())
    return h.hexdigest()


def utf8_c_bytes(s: str) -> str:
    raw = s.encode("utf-8")
    parts: list[str] = []
    pending_hex = False
    for b in raw:
        if 32 <= b < 127 and b not in (0x22, 0x5C):
            ch = chr(b)
            if pending_hex and ch in "0123456789abcdefABCDEF":
                parts.append('""')
            parts.append(ch)
            pending_hex = False
        else:
            parts.append(f"\\x{b:02x}")
            pending_hex = True
    return "".join(parts)


def field_key(unit: str, width: str) -> str:
    if width == "long":
        return unit
    return f"{unit}-{width}"


def write_relative(*, repro: bool, write_golden: bool) -> int:
    if not SRC.is_dir():
        raise SystemExit(f"missing dateFields source dir: {SRC}")

    pool: list[str] = []
    index: dict[str, int] = {}

    def intern(s: str) -> int:
        if s not in index:
            index[s] = len(pool)
            pool.append(s)
        return index[s]

    rows: list[dict] = []
    paths = sorted(SRC.rglob("dateFields.json"))
    if not paths:
        raise SystemExit(f"no dateFields.json under {SRC}")

    for path in paths:
        data = json.loads(path.read_text(encoding="utf-8"))
        main = data.get("main") or {}
        if len(main) != 1:
            raise SystemExit(f"unexpected dateFields shape: {path}")
        loc = next(iter(main))
        fields = (main[loc].get("dates") or {}).get("fields") or {}
        loc_i = intern(loc)

        for unit_i, unit in enumerate(UNITS):
            for width_i, width in enumerate(WIDTHS):
                key = field_key(unit, width)
                node = fields.get(key)
                if not isinstance(node, dict):
                    continue

                def rel(offset: int) -> int:
                    k = f"relative-type-{offset}"
                    v = node.get(k)
                    if isinstance(v, str) and v:
                        return intern(v)
                    return -1

                def patterns(side: str) -> list[int]:
                    block = node.get(f"relativeTime-type-{side}") or {}
                    out = [-1] * 6
                    if not isinstance(block, dict):
                        return out
                    for ci, cat in enumerate(PLURAL_CATS):
                        pk = f"relativeTimePattern-count-{cat}"
                        v = block.get(pk)
                        if isinstance(v, str) and v:
                            out[ci] = intern(v)
                    return out

                past = patterns("past")
                future = patterns("future")
                # Require at least "other" for one direction, or a relative keyword.
                if (
                    past[5] < 0
                    and future[5] < 0
                    and rel(-2) < 0
                    and rel(-1) < 0
                    and rel(0) < 0
                    and rel(1) < 0
                    and rel(2) < 0
                ):
                    continue

                rows.append(
                    {
                        "locale": loc_i,
                        "unit": unit_i,
                        "width": width_i,
                        "rel_m2": rel(-2),
                        "rel_m1": rel(-1),
                        "rel_0": rel(0),
                        "rel_1": rel(1),
                        "rel_2": rel(2),
                        "past": past,
                        "future": future,
                    }
                )

    rows.sort(key=lambda r: (pool[r["locale"]], r["unit"], r["width"]))

    h_text = "\n".join(
        [
            "/* Auto-generated by Tools/i18n/generate_relative.py — DO NOT EDIT. */",
            f"/* Roboticela generator {GENERATOR_VERSION} | CLDR {CLDR_VERSION} | Unicode {CLDR_UNICODE_VERSION} */",
            "#ifndef ROBO_REL_DATA_H",
            "#define ROBO_REL_DATA_H",
            "",
            "#include <stddef.h>",
            "#include <stdint.h>",
            "",
            "#ifdef __cplusplus",
            'extern "C" {',
            "#endif",
            "",
            f'#define ROBO_REL_CLDR_VERSION "{CLDR_VERSION}"',
            f'#define ROBO_REL_UNICODE_VERSION "{CLDR_UNICODE_VERSION}"',
            "",
            "/* unit: 0=year … 7=second; width: 0=long 1=short 2=narrow */",
            "/* past/future[6]: zero,one,two,few,many,other — -1 = missing */",
            "/* relative_m2/m1/0/1/2: CLDR relative-type keywords (−2…+2); -1 = absent */",
            "typedef struct robo_rel_unit {",
            "    int32_t locale;",
            "    uint8_t unit;",
            "    uint8_t width;",
            "    int32_t relative_m2;",
            "    int32_t relative_m1;",
            "    int32_t relative_0;",
            "    int32_t relative_1;",
            "    int32_t relative_2;",
            "    int32_t past[6];",
            "    int32_t future[6];",
            "} robo_rel_unit_t;",
            "",
            "extern const char *const robo_rel_strings[];",
            "extern const size_t robo_rel_string_count;",
            "extern const robo_rel_unit_t robo_rel_units[];",
            "extern const size_t robo_rel_units_count;",
            "",
            "const char *robo_rel_str(int32_t idx);",
            "const robo_rel_unit_t *robo_rel_unit_find(const char *locale, uint8_t unit, uint8_t width);",
            "const char *robo_rel_version_string(void);",
            "",
            "#ifdef __cplusplus",
            "}",
            "#endif",
            "",
            "#endif /* ROBO_REL_DATA_H */",
            "",
        ]
    )

    c_lines: list[str] = [
        "/* Auto-generated by Tools/i18n/generate_relative.py — DO NOT EDIT. */",
        f"/* CLDR {CLDR_VERSION} / Unicode {CLDR_UNICODE_VERSION} | generator {GENERATOR_VERSION} */",
        '#include "RoboI18N/RoboRelData.h"',
        "",
        "#include <string.h>",
        "",
        "const char *const robo_rel_strings[] = {",
    ]
    for s in pool:
        c_lines.append(f'    "{utf8_c_bytes(s)}",')
    c_lines.append("};")
    c_lines.append(f"const size_t robo_rel_string_count = {len(pool)};")
    c_lines.append("")
    c_lines.append("const robo_rel_unit_t robo_rel_units[] = {")
    for r in rows:
        past = ", ".join(str(x) for x in r["past"])
        fut = ", ".join(str(x) for x in r["future"])
        c_lines.append(
            "    {"
            f"{r['locale']}, {r['unit']}u, {r['width']}u, "
            f"{r['rel_m2']}, {r['rel_m1']}, {r['rel_0']}, {r['rel_1']}, {r['rel_2']}, "
            f"{{{past}}}, {{{fut}}}"
            "},"
        )
    c_lines.append("};")
    c_lines.append(f"const size_t robo_rel_units_count = {len(rows)};")
    c_lines.append("")
    c_lines.append(
        r"""
const char *robo_rel_str(int32_t idx)
{
    if (idx < 0 || (size_t)idx >= robo_rel_string_count) {
        return "";
    }
    return robo_rel_strings[idx];
}

const robo_rel_unit_t *robo_rel_unit_find(const char *locale, uint8_t unit, uint8_t width)
{
    size_t lo = 0;
    size_t hi = robo_rel_units_count;
    if (!locale) {
        return NULL;
    }
    while (lo < hi) {
        size_t mid = lo + (hi - lo) / 2u;
        const robo_rel_unit_t *row = &robo_rel_units[mid];
        int cmp = strcmp(robo_rel_strings[row->locale], locale);
        if (cmp == 0) {
            if (row->unit == unit) {
                if (row->width == width) {
                    return row;
                }
                cmp = row->width < width ? -1 : 1;
            } else {
                cmp = row->unit < unit ? -1 : 1;
            }
        }
        if (cmp < 0) {
            lo = mid + 1u;
        } else {
            hi = mid;
        }
    }
    return NULL;
}

const char *robo_rel_version_string(void)
{
    return ROBO_REL_CLDR_VERSION;
}
""".strip(
            "\n"
        )
    )

    c_text = "\n".join(c_lines) + "\n"

    if repro:
        if not OUT_H.is_file() or not OUT_C.is_file() or not GOLDEN.is_file():
            raise SystemExit("relative repro: missing outputs/golden")
        golden = json.loads(GOLDEN.read_text(encoding="utf-8"))
        if sha256_file(OUT_H) != golden["RoboRelData.h"]:
            raise SystemExit("relative repro: RoboRelData.h hash mismatch")
        if sha256_file(OUT_C) != golden["robo_rel_data.c"]:
            raise SystemExit("relative repro: robo_rel_data.c hash mismatch")
        print("relative repro OK")
        return 0

    OUT_H.parent.mkdir(parents=True, exist_ok=True)
    OUT_C.parent.mkdir(parents=True, exist_ok=True)
    OUT_H.write_text(h_text, encoding="utf-8", newline="\n")
    OUT_C.write_text(c_text, encoding="utf-8", newline="\n")

    if write_golden:
        hashes = {
            "generator": GENERATOR_VERSION,
            "cldr": CLDR_VERSION,
            "unicode": CLDR_UNICODE_VERSION,
            "RoboRelData.h": sha256_file(OUT_H),
            "robo_rel_data.c": sha256_file(OUT_C),
        }
        for path in paths:
            rel = str(path.relative_to(HERE / "source" / f"cldr-{CLDR_JSON_PACKAGE}")).replace(
                "\\", "/"
            )
            hashes[rel] = sha256_file(path)
        GOLDEN.write_text(json.dumps(hashes, indent=2, sort_keys=True) + "\n", encoding="utf-8")
        print(f"Wrote {GOLDEN.name}")

    print(
        f"Wrote relative tables: locales={len({pool[r['locale']] for r in rows})} "
        f"rows={len(rows)} pool={len(pool)} bytes_h={len(h_text.encode())} "
        f"bytes_c={len(c_text.encode())}"
    )
    return 0


def main() -> int:
    import argparse

    ap = argparse.ArgumentParser()
    ap.add_argument("--write-golden", action="store_true")
    ap.add_argument("--repro", action="store_true")
    args = ap.parse_args()
    return write_relative(repro=args.repro, write_golden=args.write_golden)


if __name__ == "__main__":
    raise SystemExit(main())
