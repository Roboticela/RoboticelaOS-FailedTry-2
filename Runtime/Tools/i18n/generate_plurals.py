#!/usr/bin/env python3
"""
Emit RoboI18N plural-rule tables + CLDR sample fixtures (Goal 4.4).

Called from generate_cldr.py so version pins stay unified.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

from plural_compile import CATEGORIES, compile_all
from robo_i18n_version import CLDR_JSON_PACKAGE, CLDR_UNICODE_VERSION, CLDR_VERSION, GENERATOR_VERSION

HERE = Path(__file__).resolve().parent
RUNTIME = HERE.parent.parent
SRC = HERE / "source" / f"cldr-{CLDR_JSON_PACKAGE}"
OUT_H = RUNTIME / "Include" / "RoboI18N" / "RoboPluralData.h"
OUT_C = RUNTIME / "Source" / "RoboI18N" / "data" / "robo_plural_data.c"
SAMPLES = RUNTIME / "Tests" / "Data" / "robo_plural_samples.txt"
GOLDEN = HERE / "plural_golden_hashes.json"


def _c_bytes(data: bytes) -> str:
    return ", ".join(f"0x{b:02x}" for b in data)


def build_plural_outputs() -> tuple[str, str, str, dict[str, str], dict[str, int]]:
    plurals_path = SRC / "supplemental" / "plurals.json"
    ordinals_path = SRC / "supplemental" / "ordinals.json"
    if not plurals_path.is_file():
        raise SystemExit(f"missing {plurals_path} — run Fetch-Cldr.ps1")
    if not ordinals_path.is_file():
        raise SystemExit(f"missing {ordinals_path} — run Fetch-Cldr.ps1")

    card_j = json.loads(plurals_path.read_text(encoding="utf-8"))
    ord_j = json.loads(ordinals_path.read_text(encoding="utf-8"))
    ver = card_j["supplemental"]["version"]
    if not str(ver.get("_cldrVersion", "")).startswith(CLDR_VERSION):
        raise SystemExit("plurals.json CLDR version mismatch")
    if str(ver.get("_unicodeVersion", "")) != CLDR_UNICODE_VERSION:
        raise SystemExit("plurals.json Unicode version mismatch")
    ver_o = ord_j["supplemental"]["version"]
    if not str(ver_o.get("_cldrVersion", "")).startswith(CLDR_VERSION):
        raise SystemExit("ordinals.json CLDR version mismatch")

    cardinal = card_j["supplemental"]["plurals-type-cardinal"]
    ordinal = ord_j["supplemental"]["plurals-type-ordinal"]
    cards, ords = compile_all(cardinal, ordinal)

    # Flatten bytecode blob + locale index
    blob = bytearray()
    card_index: list[tuple[str, int, int, int]] = []  # locale, bc_off, bc_len, n_rules
    # Per locale: rules stored as [cat:u8][len:u16][bytes...] repeated, then END cat=0xff

    def pack_locale(compiled) -> tuple[int, int, int]:
        start = len(blob)
        n_rules = 0
        for cat, bc in compiled.rules:
            if len(bc) > 0xFFFF:
                raise SystemExit(f"rule too large for {compiled.locale}")
            blob.append(cat & 0xFF)
            blob.append(len(bc) & 0xFF)
            blob.append((len(bc) >> 8) & 0xFF)
            blob.extend(bc)
            n_rules += 1
        blob.append(0xFF)  # end marker
        return start, len(blob) - start, n_rules

    for c in cards:
        off, ln, nr = pack_locale(c)
        card_index.append((c.locale, off, ln, nr))

    ord_blob_start = len(blob)
    ord_index: list[tuple[str, int, int, int]] = []
    for o in ords:
        off, ln, nr = pack_locale(o)
        ord_index.append((o.locale, off, ln, nr))

    # Sample lines: kind\tlocale\tinput\texpected
    sample_lines = ["# kind locale input expected  — generated from CLDR @integer/@decimal"]
    for c in cards:
        # Dedup while preserving order
        seen = set()
        for inp, cat in c.samples:
            key = (inp, cat)
            if key in seen:
                continue
            seen.add(key)
            sample_lines.append(f"cardinal\t{c.locale}\t{inp}\t{cat}")
    for o in ords:
        seen = set()
        for inp, cat in o.samples:
            key = (inp, cat)
            if key in seen:
                continue
            seen.add(key)
            sample_lines.append(f"ordinal\t{o.locale}\t{inp}\t{cat}")
    samples_text = "\n".join(sample_lines) + "\n"

    h_text = "\n".join(
        [
            "/* Auto-generated by Tools/i18n/generate_plurals.py — DO NOT EDIT. */",
            f"/* Roboticela generator {GENERATOR_VERSION} | CLDR {CLDR_VERSION} | Unicode {CLDR_UNICODE_VERSION} */",
            "#ifndef ROBO_PLURAL_DATA_H",
            "#define ROBO_PLURAL_DATA_H",
            "",
            "#include <stddef.h>",
            "#include <stdint.h>",
            "",
            "#ifdef __cplusplus",
            'extern "C" {',
            "#endif",
            "",
            f'#define ROBO_PLURAL_CLDR_VERSION "{CLDR_VERSION}"',
            f'#define ROBO_PLURAL_UNICODE_VERSION "{CLDR_UNICODE_VERSION}"',
            "",
            "typedef struct robo_plural_locale_index {",
            "    const char *locale;",
            "    uint32_t offset;",
            "    uint32_t length;",
            "    uint16_t rule_count;",
            "} robo_plural_locale_index_t;",
            "",
            "extern const uint8_t robo_plural_bytecode[];",
            "extern const size_t robo_plural_bytecode_size;",
            "",
            "extern const robo_plural_locale_index_t robo_plural_cardinal_index[];",
            "extern const size_t robo_plural_cardinal_index_count;",
            "",
            "extern const robo_plural_locale_index_t robo_plural_ordinal_index[];",
            "extern const size_t robo_plural_ordinal_index_count;",
            "",
            "const robo_plural_locale_index_t *robo_plural_cardinal_find(const char *locale);",
            "const robo_plural_locale_index_t *robo_plural_ordinal_find(const char *locale);",
            "",
            "#ifdef __cplusplus",
            "}",
            "#endif",
            "",
            "#endif /* ROBO_PLURAL_DATA_H */",
            "",
        ]
    )

    c_lines = [
        "/* Auto-generated by Tools/i18n/generate_plurals.py — DO NOT EDIT. */",
        f"/* CLDR {CLDR_VERSION} / Unicode {CLDR_UNICODE_VERSION} | generator {GENERATOR_VERSION} */",
        '#include "RoboI18N/RoboPluralData.h"',
        "",
        "#include <string.h>",
        "",
        "const uint8_t robo_plural_bytecode[] = {",
        "    " + _c_bytes(bytes(blob)) + ",",
        "};",
        f"const size_t robo_plural_bytecode_size = {len(blob)};",
        "",
        "const robo_plural_locale_index_t robo_plural_cardinal_index[] = {",
    ]
    for loc, off, ln, nr in card_index:
        c_lines.append(f'    {{"{loc}", {off}u, {ln}u, {nr}u}},')
    c_lines.append("};")
    c_lines.append(f"const size_t robo_plural_cardinal_index_count = {len(card_index)};")
    c_lines.append("")
    c_lines.append("const robo_plural_locale_index_t robo_plural_ordinal_index[] = {")
    for loc, off, ln, nr in ord_index:
        c_lines.append(f'    {{"{loc}", {off}u, {ln}u, {nr}u}},')
    c_lines.append("};")
    c_lines.append(f"const size_t robo_plural_ordinal_index_count = {len(ord_index)};")
    c_lines.append(
        """
static const robo_plural_locale_index_t *find_index(
    const robo_plural_locale_index_t *table,
    size_t count,
    const char *locale)
{
    size_t lo = 0;
    size_t hi = count;
    if (!locale) {
        return NULL;
    }
    while (lo < hi) {
        size_t mid = lo + (hi - lo) / 2u;
        int cmp = strcmp(locale, table[mid].locale);
        if (cmp == 0) {
            return &table[mid];
        }
        if (cmp < 0) {
            hi = mid;
        } else {
            lo = mid + 1u;
        }
    }
    return NULL;
}

const robo_plural_locale_index_t *robo_plural_cardinal_find(const char *locale)
{
    return find_index(robo_plural_cardinal_index, robo_plural_cardinal_index_count, locale);
}

const robo_plural_locale_index_t *robo_plural_ordinal_find(const char *locale)
{
    return find_index(robo_plural_ordinal_index, robo_plural_ordinal_index_count, locale);
}
"""
    )
    c_text = "\n".join(c_lines)

    checksums = {
        "plurals.json": hashlib.sha256(plurals_path.read_bytes()).hexdigest(),
        "ordinals.json": hashlib.sha256(ordinals_path.read_bytes()).hexdigest(),
    }
    stats = {
        "cardinal_locales": len(card_index),
        "ordinal_locales": len(ord_index),
        "bytecode_bytes": len(blob),
        "ordinal_blob_start": ord_blob_start,
        "samples": len(sample_lines) - 1,
        "bytes_c": len(c_text.encode("utf-8")),
    }
    return h_text, c_text, samples_text, checksums, stats


def write_plurals(*, repro: bool, write_golden: bool) -> int:
    h_text, c_text, samples_text, checksums, stats = build_plural_outputs()

    if repro:
        if not OUT_H.is_file() or not OUT_C.is_file() or not SAMPLES.is_file():
            raise SystemExit("plural repro failed: outputs missing")
        if OUT_H.read_text(encoding="utf-8") != h_text:
            raise SystemExit("plural repro failed: header differs")
        if OUT_C.read_text(encoding="utf-8") != c_text:
            raise SystemExit("plural repro failed: c differs")
        if SAMPLES.read_text(encoding="utf-8") != samples_text:
            raise SystemExit("plural repro failed: samples differ")
        if GOLDEN.is_file():
            golden = json.loads(GOLDEN.read_text(encoding="utf-8"))
            got = {
                "RoboPluralData.h": hashlib.sha256(h_text.encode("utf-8")).hexdigest(),
                "robo_plural_data.c": hashlib.sha256(c_text.encode("utf-8")).hexdigest(),
                "robo_plural_samples.txt": hashlib.sha256(
                    samples_text.encode("utf-8")
                ).hexdigest(),
            }
            for name, digest in got.items():
                if golden.get(name) != digest:
                    raise SystemExit(f"plural repro failed: golden mismatch {name}")
        print("Plural generation reproducible OK")
        print("plural stats:", json.dumps(stats))
        return 0

    OUT_H.parent.mkdir(parents=True, exist_ok=True)
    OUT_C.parent.mkdir(parents=True, exist_ok=True)
    SAMPLES.parent.mkdir(parents=True, exist_ok=True)
    OUT_H.write_text(h_text, encoding="utf-8", newline="\n")
    OUT_C.write_text(c_text, encoding="utf-8", newline="\n")
    SAMPLES.write_text(samples_text, encoding="utf-8", newline="\n")

    if write_golden:
        GOLDEN.write_text(
            json.dumps(
                {
                    "cldr_version": CLDR_VERSION,
                    "unicode_version": CLDR_UNICODE_VERSION,
                    "generator_version": GENERATOR_VERSION,
                    "RoboPluralData.h": hashlib.sha256(h_text.encode("utf-8")).hexdigest(),
                    "robo_plural_data.c": hashlib.sha256(c_text.encode("utf-8")).hexdigest(),
                    "robo_plural_samples.txt": hashlib.sha256(
                        samples_text.encode("utf-8")
                    ).hexdigest(),
                    "sources": checksums,
                },
                indent=2,
                sort_keys=True,
            )
            + "\n",
            encoding="utf-8",
            newline="\n",
        )
        print(f"Wrote {GOLDEN.name}")

    print(
        f"Wrote plural tables: cardinal={stats['cardinal_locales']} "
        f"ordinal={stats['ordinal_locales']} bytecode={stats['bytecode_bytes']} "
        f"samples={stats['samples']} bytes_c={stats['bytes_c']}"
    )
    return 0


if __name__ == "__main__":
    import sys

    args = sys.argv[1:]
    raise SystemExit(
        write_plurals(repro="--repro" in args, write_golden="--write-golden" in args)
    )
