#!/usr/bin/env python3
"""Generate compact hour-cycle preference table from CLDR timeData (Goal 4.16)."""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from robo_i18n_version import CLDR_JSON_PACKAGE, CLDR_VERSION, GENERATOR_VERSION

HERE = Path(__file__).resolve().parent
SRC = HERE / "source" / f"cldr-{CLDR_JSON_PACKAGE}" / "supplemental" / "timeData.json"
OUT = HERE.parent.parent / "Source" / "RoboI18N" / "data" / "robo_hc_data.c"
OUT_H = HERE.parent.parent / "Include" / "RoboI18N" / "RoboHcData.h"

# Map CLDR preferred skeleton letter → Unicode hc keyword.
PREF_MAP = {
    "h": "h12",
    "H": "h23",
    "K": "h11",
    "k": "h24",
    "hb": "h12",
    "hB": "h12",
}


def main() -> int:
    if not SRC.is_file():
        print(f"missing {SRC}", file=sys.stderr)
        return 1
    td = json.loads(SRC.read_text(encoding="utf-8"))["supplemental"]["timeData"]
    rows: list[tuple[str, str]] = []
    for region, info in sorted(td.items()):
        if not isinstance(info, dict):
            continue
        pref = info.get("_preferred", "H")
        # first token
        token = str(pref).split()[0]
        hc = PREF_MAP.get(token, "h23")
        rows.append((region, hc))

    h = f"""/* Auto-generated by generate_hour_cycle.py — DO NOT EDIT.
 * CLDR {CLDR_VERSION} timeData. Generator {GENERATOR_VERSION}.
 */
#ifndef ROBO_HC_DATA_H
#define ROBO_HC_DATA_H

#include <stdint.h>

#ifdef __cplusplus
extern "C" {{
#endif

typedef struct robo_hc_region {{
    const char *region; /* ISO region or "001" */
    const char *hour_cycle; /* h11 / h12 / h23 / h24 */
}} robo_hc_region_t;

extern const robo_hc_region_t robo_hc_regions[];
extern const uint32_t robo_hc_region_count;

#ifdef __cplusplus
}}
#endif

#endif /* ROBO_HC_DATA_H */
"""
    body = ",\n".join(f'    {{"{r}", "{hc}"}}' for r, hc in rows)
    c = f"""/* Auto-generated by generate_hour_cycle.py — DO NOT EDIT. */
#include "RoboI18N/RoboHcData.h"

const robo_hc_region_t robo_hc_regions[{len(rows)}] = {{
{body}
}};
const uint32_t robo_hc_region_count = {len(rows)}u;
"""
    OUT_H.parent.mkdir(parents=True, exist_ok=True)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT_H.write_text(h, encoding="utf-8", newline="\n")
    OUT.write_text(c, encoding="utf-8", newline="\n")
    print(f"hour-cycle regions={len(rows)} → {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
