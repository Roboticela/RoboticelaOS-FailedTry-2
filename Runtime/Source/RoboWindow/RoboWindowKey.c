int PhysicalKeyIsKnown(PhysicalKey key)
{
    return key > RoboPhysicalKeyUnknown && key < RoboPhysicalKeyCount;
}

int LogicalKeyIsKnown(LogicalKey key)
{
    return key > RoboLogicalKeyUnknown && key < RoboLogicalKeyCount;
}

const char *KeyActionName(KeyAction action)
{
    switch (action) {
    case RoboKeyActionNone:
        return "none";
    case RoboKeyActionDown:
        return "down";
    case RoboKeyActionUp:
        return "up";
    default:
        return "unknown";
    }
}

