int robo_demo_font_scale_clamp(int scale)
{
    return (scale < 1) ? 1 : scale;
}

robo_result_t robo_demo_fill_clipped(robo_gfx_surface_t *surface,
                                     robo_gfx_rect_t rect,
                                     robo_gfx_color_rgba8_t color)
{
    int64_t x0;
    int64_t y0;
    int64_t x1;
    int64_t y1;
    int64_t sw;
    int64_t sh;

    if (!surface) {
        return ROBO_INVALID_ARGUMENT;
    }
    if (rect.width <= 0 || rect.height <= 0) {
        return ROBO_OK; /* empty request: nothing to do */
    }
    sw = (int64_t)robo_gfx_surface_width(surface);
    sh = (int64_t)robo_gfx_surface_height(surface);

    x0 = (int64_t)rect.x;
    y0 = (int64_t)rect.y;
    x1 = x0 + (int64_t)rect.width;
    y1 = y0 + (int64_t)rect.height;

    if (x0 < 0) {
        x0 = 0;
    }
    if (y0 < 0) {
        y0 = 0;
    }
    if (x1 > sw) {
        x1 = sw;
    }
    if (y1 > sh) {
        y1 = sh;
    }
    if (x0 >= x1 || y0 >= y1) {
        return ROBO_OK; /* fully clipped away */
    }
    return robo_gfx_surface_fill_rect(
        surface, robo_gfx_rect((robo_gfx_pixel_x_t)x0, (robo_gfx_pixel_x_t)y0,
                               (int32_t)(x1 - x0), (int32_t)(y1 - y0)),
        color);
}

robo_gfx_size_t robo_demo_font_measure(const char *text,
                                       size_t length,
                                       int scale)
{
    robo_gfx_size_t size;
    int s = robo_demo_font_scale_clamp(scale);
    size_t i;
    size_t count = 0u;

    size.width = 0;
    size.height = 0;
    if (!text) {
        return size;
    }
    for (i = 0u; i < length; i++) {
        if (text[i] == '\0') {
            break;
        }
        count++;
    }
    if (count == 0u) {
        return size;
    }
    /* N glyphs advance N*(cell+gap), minus the trailing gap. */
    size.width =
        (int32_t)((count * (size_t)(ROBO_DEMO_FONT_CELL_W + ROBO_DEMO_FONT_GAP) -
                    ROBO_DEMO_FONT_GAP) *
                  (size_t)s);
    size.height = (int32_t)(ROBO_DEMO_FONT_CELL_H * s);
    return size;
}

robo_result_t robo_demo_font_draw(robo_gfx_surface_t *surface,
                                  int32_t x,
                                  int32_t y,
                                  const char *text,
                                  size_t length,
                                  int scale,
                                  robo_gfx_color_rgba8_t color)
{
    int s = robo_demo_font_scale_clamp(scale);
    int32_t pen = x;
    size_t i;

    if (!surface || !text) {
        return ROBO_INVALID_ARGUMENT;
    }
    for (i = 0u; i < length; i++) {
        unsigned char ch = (unsigned char)text[i];
        const uint8_t *glyph;
        int row;

        if (ch == '\0') {
            break;
        }
        if (ch < ROBO_DEMO_FONT_FIRST || ch > ROBO_DEMO_FONT_LAST) {
            ch = (unsigned char)'?';
        }
        glyph = g_demo_font[ch - ROBO_DEMO_FONT_FIRST];

        /* Skip glyphs entirely left/right of the surface (cheap clip). */
        if (pen + ROBO_DEMO_FONT_CELL_W * s > 0 &&
            pen < (int32_t)robo_gfx_surface_width(surface)) {
            for (row = 0; row < ROBO_DEMO_FONT_CELL_H; row++) {
                uint8_t bits = glyph[row];
                int col;

                for (col = 0; col < ROBO_DEMO_FONT_CELL_W; col++) {
                    if (bits & (0x80u >> col)) {
                        (void)robo_demo_fill_clipped(
                            surface,
                            robo_gfx_rect(pen + col * s, y + row * s, s, s),
                            color);
                    }
                }
            }
        }
        pen += (ROBO_DEMO_FONT_CELL_W + ROBO_DEMO_FONT_GAP) * s;
    }
    return ROBO_OK;
}
