int robo_physical_key_is_known(robo_physical_key_t key)
{
    return key > ROBO_PHYSICAL_KEY_UNKNOWN && key < ROBO_PHYSICAL_KEY_COUNT;
}

int robo_logical_key_is_known(robo_logical_key_t key)
{
    return key > ROBO_LOGICAL_KEY_UNKNOWN && key < ROBO_LOGICAL_KEY_COUNT;
}

const char *robo_key_action_name(robo_key_action_t action)
{
    switch (action) {
    case ROBO_KEY_ACTION_NONE:
        return "none";
    case ROBO_KEY_ACTION_DOWN:
        return "down";
    case ROBO_KEY_ACTION_UP:
        return "up";
    default:
        return "unknown";
    }
}

