#!/usr/bin/env python3
"""
Generate Unicode Extended Grapheme Cluster tables (UAX #29) for UCD 16.0.0.

Inputs:
  Tools/ucd/source/GraphemeBreakProperty.txt
  Tools/ucd/source/DerivedCoreProperties.txt  (Indic_Conjunct_Break)
  Tools/ucd/source/GraphemeBreakTest.txt

Outputs:
  Include/RoboUnicode/RoboGraphemeData.h
  Source/RoboUnicode/data/robo_grapheme_data.c
  Tests/Data/robo_grapheme_conformance.inc
"""

from __future__ import annotations

import sys
from pathlib import Path

from robo_unicode_version import UCD_VERSION

ROOT = Path(__file__).resolve().parents[2]
SRC = Path(__file__).resolve().parent / "source"
OUT_H = ROOT / "Include" / "RoboUnicode" / "RoboGraphemeData.h"
OUT_C = ROOT / "Source" / "RoboUnicode" / "data" / "robo_grapheme_data.c"
OUT_TEST = ROOT / "Tests" / "Data" / "robo_grapheme_conformance.inc"

MAX_CP = 0x110000

GB_ORDER = [
    "Other",
    "CR",
    "LF",
    "Control",
    "Extend",
    "ZWJ",
    "Regional_Indicator",
    "Prepend",
    "SpacingMark",
    "L",
    "V",
    "T",
    "LV",
    "LVT",
]

INCB_ORDER = ["None", "Consonant", "Extend", "Linker"]


def parse_cp(tok: str) -> int:
    return int(tok.strip(), 16)


def load_lines(path: Path):
    with path.open("r", encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if line:
                yield line


def parse_range(field: str) -> tuple[int, int]:
    field = field.strip()
    if ".." in field:
        a, b = field.split("..")
        return parse_cp(a), parse_cp(b)
    cp = parse_cp(field)
    return cp, cp


def compress_ranges(arr, default):
    ranges = []
    i = 0
    while i < MAX_CP:
        v = arr[i]
        j = i + 1
        while j < MAX_CP and arr[j] == v:
            j += 1
        if v != default:
            ranges.append((i, j - 1, v))
        i = j
    return ranges


def c_byte_string(b: bytes) -> str:
    return '"' + "".join(f"\\x{x:02x}" for x in b) + '"'


def main() -> int:
    gb_path = SRC / "GraphemeBreakProperty.txt"
    dcp_path = SRC / "DerivedCoreProperties.txt"
    if not gb_path.exists():
        print("Missing GraphemeBreakProperty.txt", file=sys.stderr)
        return 1

    gb_arr = [0] * MAX_CP  # Other
    gb_map = {name: i for i, name in enumerate(GB_ORDER)}

    for line in load_lines(gb_path):
        if ";" not in line:
            continue
        left, rest = line.split(";", 1)
        val = rest.split("#", 1)[0].strip()
        if val not in gb_map:
            print(f"Unknown GB value: {val}", file=sys.stderr)
            return 1
        start, end = parse_range(left)
        for cp in range(start, end + 1):
            gb_arr[cp] = gb_map[val]

    incb_arr = [0] * MAX_CP  # None
    incb_map = {name: i for i, name in enumerate(INCB_ORDER)}

    if dcp_path.exists():
        for raw in dcp_path.read_text(encoding="utf-8").splitlines():
            line = raw.split("#", 1)[0].strip()
            if not line or "InCB;" not in line:
                continue
            parts = [p.strip() for p in line.split(";")]
            if len(parts) < 2 or parts[1] != "InCB":
                continue
            val = parts[2].strip() if len(parts) > 2 else ""
            if val not in incb_map:
                continue
            start, end = parse_range(parts[0])
            for cp in range(start, end + 1):
                incb_arr[cp] = incb_map[val]

    gb_ranges = compress_ranges(gb_arr, 0)
    incb_ranges = compress_ranges(incb_arr, 0)

    OUT_H.parent.mkdir(parents=True, exist_ok=True)
    OUT_C.parent.mkdir(parents=True, exist_ok=True)

    h = [
        "/* Auto-generated by Tools/ucd/generate_grapheme.py — DO NOT EDIT. */",
        f"/* Unicode UCD version: {UCD_VERSION} — Extended Grapheme Clusters (UAX #29) */",
        "#ifndef ROBO_GRAPHEME_DATA_H",
        "#define ROBO_GRAPHEME_DATA_H",
        "",
        '#include "RoboUnicode/RoboUnicode.h"',
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
        "",
        f'#define ROBO_GRAPHEME_UCD_VERSION "{UCD_VERSION}"',
        "",
        "typedef enum robo_unicode_grapheme_break {",
    ]
    for i, name in enumerate(GB_ORDER):
        suffix = name.upper().replace(" ", "_")
        if name == "Other":
            h.append(f"    ROBO_U_GB_OTHER = {i},")
        else:
            h.append(f"    ROBO_U_GB_{suffix} = {i},")
    h.append("    ROBO_U_GB_COUNT")
    h.append("} robo_unicode_grapheme_break_t;")
    h.append("")
    h.append("typedef enum robo_unicode_incb {")
    for i, name in enumerate(INCB_ORDER):
        h.append(f"    ROBO_U_INCB_{name.upper()} = {i},")
    h.append("    ROBO_U_INCB_COUNT")
    h.append("} robo_unicode_incb_t;")
    h.append("")
    h.append("typedef struct robo_grapheme_range8 {")
    h.append("    uint32_t start;")
    h.append("    uint32_t end;")
    h.append("    uint8_t value;")
    h.append("} robo_grapheme_range8_t;")
    h.append("")
    h.append("robo_unicode_grapheme_break_t robo_grapheme_break_property(robo_uchar32_t cp);")
    h.append("robo_unicode_incb_t robo_grapheme_incb(robo_uchar32_t cp);")
    h.append("")
    h.append("#ifdef __cplusplus")
    h.append("}")
    h.append("#endif")
    h.append("")
    h.append("#endif")
    OUT_H.write_text("\n".join(h) + "\n", encoding="utf-8")

    c = [
        "/* Auto-generated by Tools/ucd/generate_grapheme.py — DO NOT EDIT. */",
        f"/* Unicode UCD {UCD_VERSION} */",
        '#include "RoboUnicode/RoboGraphemeData.h"',
        "",
        "static const robo_grapheme_range8_t robo_grapheme_gb_ranges[] = {",
    ]
    for start, end, val in gb_ranges:
        c.append(f"    {{ 0x{start:04X}u, 0x{end:04X}u, {val}u }},")
    if not gb_ranges:
        c.append("    { 0, 0, 0 },")
    c.append("};")
    c.append(f"static const size_t robo_grapheme_gb_ranges_count = {len(gb_ranges)};")
    c.append("")
    c.append("static const robo_grapheme_range8_t robo_grapheme_incb_ranges[] = {")
    for start, end, val in incb_ranges:
        c.append(f"    {{ 0x{start:04X}u, 0x{end:04X}u, {val}u }},")
    if not incb_ranges:
        c.append("    { 0, 0, 0 },")
    c.append("};")
    c.append(f"static const size_t robo_grapheme_incb_ranges_count = {len(incb_ranges)};")
    c.append(
        """
static uint8_t robo_grapheme_lookup8(const robo_grapheme_range8_t *ranges,
                                     size_t count,
                                     uint32_t cp,
                                     uint8_t default_val)
{
    size_t lo = 0, hi = count;
    while (lo < hi) {
        size_t mid = lo + (hi - lo) / 2u;
        const robo_grapheme_range8_t *r = &ranges[mid];
        if (cp < r->start) {
            hi = mid;
        } else if (cp > r->end) {
            lo = mid + 1u;
        } else {
            return r->value;
        }
    }
    return default_val;
}

robo_unicode_grapheme_break_t robo_grapheme_break_property(robo_uchar32_t cp)
{
    return (robo_unicode_grapheme_break_t)robo_grapheme_lookup8(
        robo_grapheme_gb_ranges, robo_grapheme_gb_ranges_count, cp, 0);
}

robo_unicode_incb_t robo_grapheme_incb(robo_uchar32_t cp)
{
    return (robo_unicode_incb_t)robo_grapheme_lookup8(
        robo_grapheme_incb_ranges, robo_grapheme_incb_ranges_count, cp, 0);
}
"""
    )
    OUT_C.write_text("\n".join(c) + "\n", encoding="utf-8")
    print(f"Wrote {OUT_H} and {OUT_C} (gb_ranges={len(gb_ranges)} incb_ranges={len(incb_ranges)})")

    test_path = SRC / "GraphemeBreakTest.txt"
    if test_path.exists():
        cases = []
        for raw in test_path.read_text(encoding="utf-8").splitlines():
            line = raw.split("#", 1)[0].strip()
            if not line or line.startswith("@"):
                continue
            tokens = line.split()
            cps = []
            breaks = []
            pending_break = None
            for tok in tokens:
                if tok == "÷":
                    pending_break = 1
                elif tok == "×":
                    pending_break = 0
                else:
                    if pending_break is None:
                        pending_break = 1
                    breaks.append(pending_break)
                    cps.append(parse_cp(tok))
                    pending_break = None
            if cps:
                cases.append((cps, breaks))

        lines = [
            "/* Auto-generated from GraphemeBreakTest.txt — DO NOT EDIT. */",
            f"/* Unicode {UCD_VERSION}, {len(cases)} cases */",
            "typedef struct robo_grapheme_conf_case {",
            "    const robo_uchar32_t *cps;",
            "    const unsigned char *breaks;",
            "    unsigned cp_count;",
            "} robo_grapheme_conf_case_t;",
            "",
        ]
        cp_pool = []
        br_pool = []
        for cps, brs in cases:
            cp_off = len(cp_pool)
            br_off = len(br_pool)
            cp_pool.extend(cps)
            cp_pool.append(0xFFFFFFFF)  # sentinel between cases
            br_pool.extend(brs)
            br_pool.append(255)
        lines.append("static const robo_uchar32_t robo_grapheme_conf_cps[] = {")
        for i in range(0, len(cp_pool), 8):
            chunk = cp_pool[i : i + 8]
            lines.append("    " + ", ".join(f"0x{x:08X}u" for x in chunk) + ",")
        lines.append("};")
        lines.append("static const unsigned char robo_grapheme_conf_breaks[] = {")
        for i in range(0, len(br_pool), 16):
            chunk = br_pool[i : i + 16]
            lines.append("    " + ", ".join(str(x) for x in chunk) + ",")
        lines.append("};")
        lines.append("static const robo_grapheme_conf_case_t robo_grapheme_conf_cases[] = {")
        cp_i = 0
        br_i = 0
        for cps, brs in cases:
            n = len(cps)
            lines.append(
                f"    {{ robo_grapheme_conf_cps + {cp_i}, robo_grapheme_conf_breaks + {br_i}, {n}u }},"
            )
            cp_i += n + 1
            br_i += n + 1
        lines.append("};")
        lines.append(
            f"static const size_t robo_grapheme_conf_cases_count = {len(cases)};"
        )
        OUT_TEST.parent.mkdir(parents=True, exist_ok=True)
        OUT_TEST.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"Wrote {OUT_TEST} ({len(cases)} cases)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
