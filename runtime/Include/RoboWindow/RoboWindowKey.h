typedef enum robo_key_action {
    ROBO_KEY_ACTION_NONE = 0,
    ROBO_KEY_ACTION_DOWN = 1,
    ROBO_KEY_ACTION_UP = 2
} robo_key_action_t;

/** Modifier bit flags (Roboticela-owned). */
typedef uint32_t robo_key_modifier_flags_t;

#define ROBO_KEY_MOD_NONE          ((robo_key_modifier_flags_t)0u)
#define ROBO_KEY_MOD_SHIFT         ((robo_key_modifier_flags_t)(1u << 0))
#define ROBO_KEY_MOD_CTRL          ((robo_key_modifier_flags_t)(1u << 1))
#define ROBO_KEY_MOD_ALT           ((robo_key_modifier_flags_t)(1u << 2))
#define ROBO_KEY_MOD_META          ((robo_key_modifier_flags_t)(1u << 3))
#define ROBO_KEY_MOD_CAPS_LOCK     ((robo_key_modifier_flags_t)(1u << 4))
#define ROBO_KEY_MOD_NUM_LOCK      ((robo_key_modifier_flags_t)(1u << 5))
#define ROBO_KEY_MOD_SCROLL_LOCK   ((robo_key_modifier_flags_t)(1u << 6))
#define ROBO_KEY_MOD_SHIFT_LEFT    ((robo_key_modifier_flags_t)(1u << 7))
#define ROBO_KEY_MOD_SHIFT_RIGHT   ((robo_key_modifier_flags_t)(1u << 8))
#define ROBO_KEY_MOD_CTRL_LEFT     ((robo_key_modifier_flags_t)(1u << 9))
#define ROBO_KEY_MOD_CTRL_RIGHT    ((robo_key_modifier_flags_t)(1u << 10))
#define ROBO_KEY_MOD_ALT_LEFT      ((robo_key_modifier_flags_t)(1u << 11))
#define ROBO_KEY_MOD_ALT_RIGHT     ((robo_key_modifier_flags_t)(1u << 12))
#define ROBO_KEY_MOD_META_LEFT     ((robo_key_modifier_flags_t)(1u << 13))
#define ROBO_KEY_MOD_META_RIGHT    ((robo_key_modifier_flags_t)(1u << 14))

