import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { createRequire } from "node:module";
import { buildSync } from "esbuild";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const repo = join(root, "..");
const cssPath = join(root, "src", "desktop.css");
const outDir = join(repo, "Build", "Desktop", "Ui");
const generatedDir = join(repo, "Runtime", "Source", "RoboDesktop", "Generated");
const headerPath = join(generatedDir, "DesktopPage.h");
const bundlePath = join(outDir, "ssr.cjs");

mkdirSync(outDir, { recursive: true });
mkdirSync(generatedDir, { recursive: true });

buildSync({
  absWorkingDir: root,
  entryPoints: [join(root, "scripts", "ssr-entry.jsx")],
  bundle: true,
  platform: "node",
  format: "cjs",
  outfile: bundlePath,
  jsx: "automatic",
});

const require = createRequire(pathToFileURL(bundlePath).href);
const { renderDesktopHtml } = require(bundlePath);

const inner = renderDesktopHtml();
const markup = `<html><body>${inner}</body></html>`
  .replace(/class="/g, "class='")
  .replace(/"/g, "'");
const style = readFileSync(cssPath, "utf8").replace(/\s+/g, " ").trim();

function cString(text) {
  return text
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\r\n/g, "\\n")
    .replace(/\n/g, "\\n")
    .replace(/\r/g, "\\n");
}

const htmlOut = join(outDir, "desktop.html");
const cssOut = join(outDir, "desktop.css");
const jsOut = join(outDir, "desktop.js");
writeFileSync(htmlOut, markup, "utf8");
writeFileSync(cssOut, `${style}\n`, "utf8");
writeFileSync(
  jsOut,
  "/* RoboticelaOS desktop script. Guest JavaScript execution is Phase 13; this file is the compiled preview artifact. */\n",
  "utf8"
);

const header = `/* Generated by Desktop/scripts/export-page.mjs — do not edit by hand. */\n#ifndef ROBO_DESKTOP_PAGE_H\n#define ROBO_DESKTOP_PAGE_H\n\nstatic const char kDesktopPageMarkup[] =\n    "${cString(markup)}";\n\nstatic const char kDesktopPageStyle[] =\n    "${cString(style)}";\n\n#endif /* ROBO_DESKTOP_PAGE_H */\n`;
writeFileSync(headerPath, header, "utf8");
console.log(`wrote ${headerPath}`);
console.log(`wrote ${htmlOut}`);
