/* §40 — absence and malformed input                                    */
/* ------------------------------------------------------------------ */

/** A font with no GSUB, no GPOS and no GDEF shapes through the `cmap` alone, and says so in its mode. */
static void TestShapingNoLayoutTables(void)
{
    ConfFontSpec spec;
    ConfFace face;
    RoboTextShapeResult *result;

    ConfSpecEuropean(&spec);
    spec.omitGsub = 1;
    spec.omitGpos = 1;
    spec.omitGdef = 1;
    ConfFaceOpen(&face, &spec, IntegrationSizePx);
    result = ConfShapeDefault(&face, "office AV e\xCC\x81");
    /* The glyphs are the `cmap`'s own: 6 + 1 + 2 + 1 + 2 scalars, each its own glyph. */
    ConfExpectGlyphCount(result, 12u, "text.shaping.integration.no_layout_tables", "office AV e+acute");
    RoboCheckEqInt((int)ConfTotalSubstituted(result), 0);
    RoboCheckEqInt((int)ConfTotalLigatures(result), 0);
    RoboCheckEqInt((int)ConfTotalPositioned(result), 0);
    RoboCheckEqInt((int)ConfTotalMissing(result), 0);
    for (size_t run = 0u; run < RoboTextShapeResultGlyphRunCount(result); run++) {
        RoboCheckEqInt((int)RoboTextGlyphRunGenerationMode(RoboTextShapeResultGlyphRun(result, run)),
                       (int)RoboTextGlyphGenerationCmapPerScalar);
    }
    ConfExpectValid(result, "text.shaping.integration.no_layout_tables");
    /* And the width is the un-kerned, un-ligated sum — the same numbers, reached differently. */
    {
        double expected = 0.0;

        for (size_t i = 0u; i < 12u; i++) {
            const RoboTextGlyph *glyph = ConfGlyphAt(result, i);

            RoboCheck(glyph != NULL);
            expected += (double)glyph->advanceX;
        }
        ConfExpectFloatClose(ConfTotalAdvance(result), (float)expected,
                             "text.shaping.integration.no_layout_tables", "the summed width");
    }
    RoboTextShapeResultDestroy(result);
    ConfFaceClose(&face);
}

/**
 * A directory entry that points past the end of the source is **skipped, counted, and shaped around**.
 *
 * This is §40's malformed half, and the shape of the failure is deliberate: only the *directory entry* is
 * patched, so the GSUB table's bytes are still in the file and a reader that ignored the entry's bounds would
 * find plausible data past the end of an unrelated buffer. The promise — a font's contents never fail a call —
 * is checked by shaping the same text that the intact fixture ligates and requiring the *unligated* answer,
 * not by looking for a crash.
 */
static void TestShapingMalformedTable(void)
{
    ConfFontSpec spec;
    ConfFace face;
    RoboTextShapeResult *result;
    uint32_t gsubTag = RoboFontTag('G', 'S', 'U', 'B');
    uint32_t gsubLength = 0u;
    uint8_t *gsub;

    ConfSpecEuropean(&spec);
    memset(&face, 0, sizeof(face));
    ConfFaceBuildBytes(&face, &spec);
    gsub = ConfFaceTableBytes(&face, gsubTag, &gsubLength);
    RoboCheck(gsub != NULL && gsubLength >= 12u);
    /* The directory entry stays honest — offset and length untouched — and the corruption is *inside* the
     * table: the first lookup's subtable offset is moved to the lookup's own header.
     *
     * That is the shape the engines explicitly refuse (`RoboTextOtSubtableInsideLookup`): a subtable that
     * lands inside its own lookup is a forward reference to nowhere, and a reader that followed it would read
     * the lookup's type word as a substitution format. The plan still resolves — the ScriptList, the
     * LangSys and the FeatureList are all intact — so what the case proves is that a malformed *lookup* is
     * skipped and the rest of the font still applies, which is the promise "a font's contents never fail a
     * call". */
    {
        uint16_t lookupListOffset = (uint16_t)(((uint16_t)gsub[8] << 8) | gsub[9]);
        uint16_t firstLookup;
        size_t subtableField;

        RoboCheck((size_t)lookupListOffset + 6u <= (size_t)gsubLength);
        firstLookup = (uint16_t)(((uint16_t)gsub[lookupListOffset + 2u] << 8) |
                                 gsub[lookupListOffset + 3u]);
        subtableField = (size_t)lookupListOffset + (size_t)firstLookup + 6u;
        RoboCheck(subtableField + 1u < (size_t)gsubLength);
        gsub[subtableField] = 0u;
        gsub[subtableField + 1u] = 0u;
    }
    ConfFaceAdopt(&face, IntegrationSizePx);
    result = ConfShapeDefault(&face, "office");
    /* Nothing folded, because no lookup could be read — and the text is still six drawable glyphs. */
    ConfExpectGlyphCount(result, 6u, "text.shaping.integration.malformed_table", "office");
    RoboCheckEqInt((int)ConfTotalLigatures(result), 0);
    RoboCheckEqInt((int)ConfTotalMissing(result), 0);
    ConfExpectValid(result, "text.shaping.integration.malformed_table");
    /* The GPOS half is untouched by the patch, so the pair still applies: the case is about *one* table
     * being unreadable, not about the face being degraded. */
    RoboTextShapeResultDestroy(result);
    result = ConfShapeDefault(&face, "AV");
    RoboCheck(ConfTotalPositioned(result) >= 1u);
    RoboTextShapeResultDestroy(result);
    /* A directory entry that points outside the source is a *different* failure and is refused whole: the
     * loader cannot trust a font whose own contents lie about their location, so the case checks the
     * refusal rather than expecting a usable face. */
    {
        ConfFace broken;
        FontSource *source = NULL;
        FontFace *brokenFace = NULL;

        memset(&broken, 0, sizeof(broken));
        ConfFaceBuildBytes(&broken, &spec);
        RoboCheckEqInt(ConfFacePatchTableOffset(&broken, gsubTag, 0xFFFFFF00u), 1);
        if (FontSourceCreateMemoryCopy(broken.bytes, broken.length, &source) == RoboOk) {
            Result created = FontFaceCreate(source, 0u, &brokenFace);

            RoboCheckMsg(created != RoboOk || FontFaceParseCmap(brokenFace) != RoboOk,
                         "a font whose directory points outside itself was accepted as usable");
            FontFaceRelease(brokenFace);
        }
        FontSourceRelease(source);
    }
}

