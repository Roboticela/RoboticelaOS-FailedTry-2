#define IntegrationDumpPath "Build/Text-ShapingConformance.txt"

/**
 * Write the corpus, its features and its answers to @ref IntegrationDumpPath, and assert the file's own
 * arithmetic.
 *
 * Machine-readable reference data (§32) generated by the shipping path rather than by an external shaper, so
 * a regression is a diff in a small text file. The file states, per case: the label, the UTF-8 text, the run
 * count, each run's script and direction, each glyph's id/source/advance/offset, and the clusters — the same
 * facts the assertions above check, in a form a human can read and a script can diff.
 */
static void TestShapingIntegrationDump(void)
{
    ConfFontSpec spec;
    ConfFace face;
    FILE *file;
    size_t cases = 0u;

    ConfSpecEuropean(&spec);
    ConfFaceOpen(&face, &spec, IntegrationSizePx);
    file = fopen(IntegrationDumpPath, "wb");
    RoboCheckMsg(file != NULL, "the conformance dump could not be opened");
    fprintf(file, "RoboText shaping conformance (Phase 12.18)\n");
    fprintf(file, "font: conformance-european  upem 1000  size 16px\n\n");
    for (size_t i = 0u; i < sizeof(kIntegrationCorpus) / sizeof(kIntegrationCorpus[0]); i++) {
        RoboTextShapeResult *result = IntegrationShape(&face, kIntegrationCorpus[i].text);
        const RoboTextMeasurement *measurement = RoboTextShapeResultMeasurement(result);

        fprintf(file, "case %s\n", kIntegrationCorpus[i].label);
        fprintf(file, "  text \"%s\"\n", kIntegrationCorpus[i].text);
        fprintf(file, "  runs %u  glyphs %u  missing %u  ligatures %u  positioned %u\n",
                (unsigned)RoboTextShapeResultGlyphRunCount(result), (unsigned)ConfTotalGlyphs(result),
                (unsigned)ConfTotalMissing(result), (unsigned)ConfTotalLigatures(result),
                (unsigned)ConfTotalPositioned(result));
        fprintf(file, "  width %.4f\n", (double)measurement->width);
        for (size_t run = 0u; run < RoboTextShapeResultGlyphRunCount(result); run++) {
            const RoboTextGlyphRun *glyphRun = RoboTextShapeResultGlyphRun(result, run);
            RoboTextRange source = RoboTextGlyphRunSourceRange(glyphRun);

            fprintf(file, "  run %u  source [%u..%u)  script %s  direction %s  level %d\n",
                    (unsigned)run, (unsigned)source.start, (unsigned)source.end,
                    RoboTextScriptName(RoboTextGlyphRunScript(glyphRun)),
                    RoboTextDirectionName(RoboTextGlyphRunDirection(glyphRun)),
                    (int)RoboTextGlyphRunBidiLevel(glyphRun));
            for (size_t g = 0u; g < RoboTextGlyphRunCount(glyphRun); g++) {
                const RoboTextGlyph *glyph = RoboTextGlyphRunGlyph(glyphRun, (RoboTextGlyphIndex)g);

                fprintf(file, "    glyph %u id %u source [%u..%u) advance %.4f offset %.4f,%.4f%s\n",
                        (unsigned)g, (unsigned)glyph->glyphId, (unsigned)glyph->source.start,
                        (unsigned)glyph->source.end, (double)glyph->advanceX, (double)glyph->offsetX,
                        (double)glyph->offsetY, glyph->ligatureComponents ? "  ligature" : "");
            }
            for (size_t c = 0u; c < RoboTextGlyphRunClusterCount(glyphRun); c++) {
                const RoboTextGlyphCluster *cluster =
                    RoboTextGlyphRunCluster(glyphRun, (RoboTextClusterIndex)c);

                fprintf(file, "    cluster %u source [%u..%u) glyphs [%u..%u)\n", (unsigned)c,
                        (unsigned)cluster->source.start, (unsigned)cluster->source.end,
                        (unsigned)cluster->glyphStart, (unsigned)cluster->glyphEnd);
            }
        }
        /* The file's own arithmetic: what it printed as the width is the measurement it read. */
        RoboCheckEqInt((int)measurement->glyphCount, (int)ConfTotalGlyphs(result));
        cases++;
        RoboTextShapeResultDestroy(result);
    }
    fclose(file);
    RoboCheckEqInt((int)cases, (int)(sizeof(kIntegrationCorpus) / sizeof(kIntegrationCorpus[0])));
    ConfFaceClose(&face);
}

