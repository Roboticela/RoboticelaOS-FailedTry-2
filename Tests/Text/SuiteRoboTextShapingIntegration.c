/** Shape the corpus a hundred times and report the cost, so a future regression has a number to beat. */
static void TestShapingIntegrationPerformance(void)
{
    ConfFontSpec spec;
    ConfFace face;
    clock_t start;
    clock_t end;
    size_t glyphs = 0u;
    const size_t passes = 100u;

    ConfSpecEuropean(&spec);
    ConfFaceOpen(&face, &spec, IntegrationSizePx);
    start = clock();
    for (size_t pass = 0u; pass < passes; pass++) {
        for (size_t i = 0u; i < sizeof(kIntegrationCorpus) / sizeof(kIntegrationCorpus[0]); i++) {
            RoboTextShapeResult *result = IntegrationShape(&face, kIntegrationCorpus[i].text);

            glyphs += ConfTotalGlyphs(result);
            RoboTextShapeResultDestroy(result);
        }
    }
    end = clock();
    fprintf(stdout, "text.shaping.integration.performance: %u cases x %u passes -> %u glyphs in %ld ms\n",
            (unsigned)(sizeof(kIntegrationCorpus) / sizeof(kIntegrationCorpus[0])), (unsigned)passes,
            (unsigned)glyphs, (long)((end - start) * 1000 / CLOCKS_PER_SEC));
    fflush(stdout);
    RoboCheck(glyphs > 0u);
    RoboCheck((end - start) >= 0);
    ConfFaceClose(&face);
}

