/* §28 — a European line with an Arabic interruption                    */
/* ------------------------------------------------------------------ */

/**
 * `Hello (مرحبا) world`: the Latin stays left-to-right, the Arabic becomes an RTL run, the source order stays
 * logical, and the brackets mirror.
 *
 * The fixture's `cmap` has no Arabic, so the Arabic scalars are `.notdef` — which the case states rather than
 * hides (`missingGlyphs` is asserted non-zero). What is being checked is the *structure*: more than one run, at
 * least one of them right-to-left, every run's source range inside the text and starting at 0 for the first,
 * and L4 visible as a mirrored glyph, because a `(` in a right-to-left context draws as `)`.
 */
/**
 * The invariants every mixed LTR/RTL case shares: the runs tile the text in **logical** order.
 *
 * An L2 performed inside the shaping layer would show up here as an out-of-order or overlapping source range
 * — which is the defect this helper exists to catch, and the reason the order of the glyphs is not what is
 * asserted (a run's glyphs are in logical order within the run; the *runs* are what a visual order would
 * permute).
 */
static void IntegrationCheckRunTiling(const RoboTextShapeResult *result, const char *label,
                                     size_t *outRtl, size_t *outMirrored)
{
    RoboTextScalarIndex at = 0u;

    for (size_t run = 0u; run < RoboTextShapeResultGlyphRunCount(result); run++) {
        const RoboTextGlyphRun *glyphRun = RoboTextShapeResultGlyphRun(result, run);
        RoboTextRange range = RoboTextGlyphRunSourceRange(glyphRun);

        if (range.start != at || range.end <= range.start) {
            ConfReport(label, "", "run source tiling", "contiguous ascending ranges", "gaps or overlaps");
            RoboCheckMsg(0, "the runs do not tile the text in logical order");
            return;
        }
        at = range.end;
        if (RoboTextGlyphRunDirection(glyphRun) == RoboTextDirectionRtl) {
            (*outRtl)++;
        }
        *outMirrored += RoboTextGlyphRunMirrored(glyphRun);
    }
}

/**
 * `Hello مرحبا world` (§28): the Latin stays left-to-right, the Arabic becomes a right-to-left run, and the
 * source stays logical.
 *
 * The fixture's `cmap` has no Arabic, so the Arabic scalars are `.notdef` — stated rather than hidden
 * (`missingGlyphs` is asserted non-zero, and `substituted` zero, because an unmapped scalar is not a reason
 * for GSUB to have done anything). What the case is *about* is the run structure: both directions present,
 * and the runs tiling the text in source order.
 */
static void TestShapingRtlBoundary(void)
{
    /* "Hello مرحبا world" */
    static const char kText[] = "Hello \xD9\x85\xD8\xB1\xD8\xAD\xD8\xA8\xD8\xA7 world";
    ConfFontSpec spec;
    ConfFace face;
    RoboTextShapeOptions options;
    RoboTextShapeResult *result;
    size_t rtlRuns = 0u;
    size_t mirrored = 0u;
    size_t ltrRuns = 0u;

    ConfSpecEuropean(&spec);
    ConfFaceOpen(&face, &spec, IntegrationSizePx);
    RoboTextShapeOptionsInit(&options);
    options.baseDirection = RoboTextDirectionLtr;
    result = ConfShape(&face, kText, &options);
    RoboCheck(RoboTextShapeResultGlyphRunCount(result) >= 2u);
    IntegrationCheckRunTiling(result, "text.shaping.integration.rtl_boundary", &rtlRuns, &mirrored);
    {
        RoboTextView view = ConfView(kText);
        RoboTextScalarIndex scalars = 0u;
        RoboTextScalarIndex covered = 0u;

        RoboCheckEqInt((int)RoboTextViewScalarCount(view, &scalars, NULL), (int)RoboOk);
        for (size_t run = 0u; run < RoboTextShapeResultGlyphRunCount(result); run++) {
            RoboTextRange range = RoboTextGlyphRunSourceRange(RoboTextShapeResultGlyphRun(result, run));

            covered = range.end;
            if (RoboTextGlyphRunDirection(RoboTextShapeResultGlyphRun(result, run)) ==
                RoboTextDirectionLtr) {
                ltrRuns++;
            }
        }
        RoboCheckEqInt((int)covered, (int)scalars);
    }
    RoboCheckMsg(rtlRuns >= 1u, "the Arabic inside a Latin line produced no right-to-left run");
    RoboCheckMsg(ltrRuns >= 1u, "the Latin around the Arabic produced no left-to-right run");
    /* The Arabic scalars are not in the fixture's cmap, which the case says out loud. */
    RoboCheck(ConfTotalMissing(result) > 0u);
    RoboCheckEqInt((int)ConfTotalSubstituted(result), 0);
    ConfExpectValid(result, "text.shaping.integration.rtl_boundary");
    RoboTextShapeResultDestroy(result);
    ConfFaceClose(&face);
}

/**
 * L4's mirroring, where it actually applies.
 *
 * A bracket is drawn mirrored exactly when its **resolved level is odd**, and a bracket between two Latin
 * runs resolves with the base — even — which is why the case above cannot show it and says nothing about it.
 * The text here is two right-to-left words with a bracketed pair between them and **no spaces**: pure `R`
 * context on both sides, so the brackets resolve to an odd level and are depicted by their mirrored code
 * point. The source is untouched, which is what makes selection and copy still see `(`.
 */
static void TestShapingMirroring(void)
{
    /* "مرحبا(שלום)" */
    static const char kText[] = "\xD9\x85\xD8\xB1\xD8\xAD\xD8\xA8\xD8\xA7"
                                "(\xD7\xA9\xD7\x9C\xD7\x95\xD7\x9D)";
    ConfFontSpec spec;
    ConfFace face;
    RoboTextShapeOptions options;
    RoboTextShapeResult *result;
    size_t rtlRuns = 0u;
    size_t mirrored = 0u;

    ConfSpecEuropean(&spec);
    ConfFaceOpen(&face, &spec, IntegrationSizePx);
    RoboTextShapeOptionsInit(&options);
    options.baseDirection = RoboTextDirectionLtr;
    result = ConfShape(&face, kText, &options);
    IntegrationCheckRunTiling(result, "text.shaping.integration.mirroring", &rtlRuns, &mirrored);
    RoboCheckMsg(rtlRuns >= 1u, "an all-Arabic-and-Hebrew text produced no right-to-left run");
    /* One mirror for each bracket, and the `(` is still the scalar the glyph's source names. */
    RoboCheckMsg(mirrored >= 1u, "no bracket in the right-to-left context was drawn mirrored");
    {
        int found = 0;

        for (size_t i = 0u; i < ConfTotalGlyphs(result); i++) {
            const RoboTextGlyph *glyph = ConfGlyphAt(result, i);

            if (glyph == NULL || !glyph->mirrored) {
                continue;
            }
            found = 1;
            /* The glyph is the *mirrored* code point's, and the record still points at the scalar.
             * Parentheses: U+0028 mirrors to U+0029 and back, so either id is legitimate here. */
            RoboCheck(glyph->glyphId == ConfGlyphOf(0x0028u) || glyph->glyphId == ConfGlyphOf(0x0029u));
        }
        RoboCheckEqInt(found, 1);
    }
    ConfExpectValid(result, "text.shaping.integration.mirroring");
    RoboTextShapeResultDestroy(result);
    ConfFaceClose(&face);
}

/* ------------------------------------------------------------------ */
/* §37 — the pen the painter walks is the run's own prefix sum         */
/* ------------------------------------------------------------------ */

/**
 * The pen position at glyph @p i is the sum of the glyphs before it, and the glyph's origin is that plus its
 * own placement offset.
 *
 * The phase's §37 asks that the positions RoboText tests are the positions `DrawGlyphRun` consumes, with no
 * second positioning calculation in paint. The checkable form of that promise is here: `AdvanceUpTo` — the
 * door a caret and a painter both use — must *equal* the running sum of the glyphs' own advances, and each
 * glyph's origin must be that prefix plus its `offsetX`. A paint layer that re-derived either (by re-reading
 * `hmtx`, or by re-applying a kern) would produce a number this case can catch, and the kerning text is in
 * the corpus precisely because it is the case where a second calculation would differ.
 */
static void TestShapingPenAgrees(void)
{
    ConfFontSpec spec;
    ConfFace face;

    ConfSpecEuropean(&spec);
    ConfFaceOpen(&face, &spec, IntegrationSizePx);
    for (size_t i = 0u; i < sizeof(kIntegrationCorpus) / sizeof(kIntegrationCorpus[0]); i++) {
        RoboTextShapeResult *result = IntegrationShape(&face, kIntegrationCorpus[i].text);

        for (size_t run = 0u; run < RoboTextShapeResultGlyphRunCount(result); run++) {
            const RoboTextGlyphRun *glyphRun = RoboTextShapeResultGlyphRun(result, run);
            double pen = 0.0;

            for (size_t g = 0u; g < RoboTextGlyphRunCount(glyphRun); g++) {
                const RoboTextGlyph *glyph = RoboTextGlyphRunGlyph(glyphRun, (RoboTextGlyphIndex)g);
                float prefix = 0.0f;

                RoboCheckEqInt((int)RoboTextGlyphRunAdvanceUpTo(glyphRun, (RoboTextGlyphIndex)g, &prefix,
                                                               NULL),
                               (int)RoboOk);
                /* The prefix the run answers with is the sum the painter would accumulate, to the last bit
                 * of the `double` accumulation — not merely close to it. */
                if (prefix != (float)pen) {
                    ConfReport("text.shaping.integration.pen_agrees", kIntegrationCorpus[i].label,
                               "pen position", "the running sum of the glyphs' advances",
                               "a different number");
                    RoboCheckMsg(0, "the run's prefix sum disagrees with its glyphs' advances");
                    break;
                }
                /* The origin is the pen plus the font's own placement, which is already in the offset. */
                RoboCheck(glyph->offsetAdjustX == glyph->offsetX ||
                          (glyph->offsetX - glyph->offsetAdjustX) < ConfPositionTolerance);
                pen += (double)glyph->advanceX;
            }
            ConfExpectFloatClose((float)pen, RoboTextGlyphRunAdvance(glyphRun),
                                 "text.shaping.integration.pen_agrees", kIntegrationCorpus[i].label);
        }
        ConfExpectValid(result, "text.shaping.integration.pen_agrees");
        RoboTextShapeResultDestroy(result);
    }
    ConfFaceClose(&face);
}

