/*
 * Shaping integration conformance (Phase 12.18) — `text.shaping.integration.*`.
 *
 * The phase's §28, §36, §38, §39, §40 and §46. Every case here is about a *seam* rather than a stage:
 *
 *   - **measurement and shaping agree** (§36): the width the measurement reports is the sum of the glyph
 *     runs' own advances, and the measure door re-run over the same list answers the same number. Two readers
 *     of one answer, which is what keeps the pen and the measurer from drifting;
 *   - **clusters survive** (§38): the cluster array tiles the source and the glyphs before *and* after a
 *     second measurement, so nothing between shaping and paint renumbers a cluster;
 *   - **the same input is the same bytes** (§39), across a rebuilt face and across a full pass over the
 *     conformance corpus;
 *   - **a font with no layout tables is shaped, not refused** (§40's absence half), and **a font whose
 *     directory points past the end of its own source is skipped and counted** (the malformed half) — the
 *     shaping continues with what the `cmap` gave;
 *   - **a European line with an Arabic interruption** (§28) keeps its logical source order and produces an
 *     RTL run, with L4's mirrored brackets visible and the base Latin untouched.
 *
 * The last case writes `Build/Text-ShapingConformance.txt`: the corpus, its expectations and its answers,
 * which is the deterministic reference data §32 and §46 ask for. It is generated by the *shipping* code path
 * — `RoboTextShape` — rather than by a reference shaper, so a regression shows up as a diff in a file that
 * is cheap to read.
 */

#include "RoboTextConformanceSupport.h"

#include <stdio.h>
#include <string.h>
#include <time.h>

#define IntegrationSizePx 16.0f

/** The corpus. One list, so the dump, the determinism pass and the performance case cannot disagree. */
typedef struct IntegrationCorpus {
    const char *label;
    const char *text;
} IntegrationCorpus;

static const IntegrationCorpus kIntegrationCorpus[] = {
    {"latin.basic", "The quick brown fox jumps over the lazy dog."},
    {"latin.digits", "0123456789"},
    {"latin.punctuation", "Hello, world! (2026) \xE2\x80\x94 \"quoted\""},
    {"latin.extended", "\xC3\xA4\xC3\xB6\xC3\xBC \xC3\xA9\xC3\xA0\xC3\xA7\xC3\xB1 \xC3\x9F\xC3\xB8\xC5\x82\xC5\x93"},
    {"latin.ligature", "office ffl ffi configuration"},
    {"latin.kerning", "AV VA To Ta Wa"},
    {"latin.marks", "e\xCC\x81 a\xCC\x80 o\xCC\x88 n\xCC\x83"},
    {"greek", "\xCE\x91\xCE\xBB\xCF\x86\xCE\xB1 \xCE\x95\xCE\xBB\xCE\xBB\xCE\xB1\xCE\xB4\xCE\xB1"},
    {"cyrillic", "\xD0\x9F\xD1\x80\xD0\xB8\xD0\xB2\xD0\xB5\xD1\x82 \xD0\x9C\xD0\xB8\xD1\x80"},
    {"mixed.scripts", "Latin \xCE\x95\xCE\xBB\xCE\xBB\xCE\xB1\xCE\xB4\xCE\xB1 "
                      "\xD0\x9A\xD0\xB8\xD1\x80\xD0\xB8\xD0\xBB\xD0\xBB\xD0\xB8\xD1\x86\xD0\xB0"},
    {"mixed.rtl", "Hello (\xD9\x85\xD8\xB1\xD8\xAD\xD8\xA8\xD8\xA7) world"},
    {"control.space", "a b\xC2\xA0" "c"},
};

/** Shape one corpus entry over a default face. */
static RoboTextShapeResult *IntegrationShape(const ConfFace *face, const char *text)
{
    RoboTextShapeOptions options;

    RoboTextShapeOptionsInit(&options);
    options.baseDirection = RoboTextDirectionLtr;
    return ConfShape(face, text, &options);
}

/* ------------------------------------------------------------------ */
/* §36 — measurement agrees with the shaped advances                    */
/* ------------------------------------------------------------------ */

/** The measurement is the sum of the runs' advances, and the measure door answers the same number. */
static void TestShapingMeasurementAgrees(void)
{
    ConfFontSpec spec;
    ConfFace face;

    ConfSpecEuropean(&spec);
    ConfFaceOpen(&face, &spec, IntegrationSizePx);
    for (size_t i = 0u; i < sizeof(kIntegrationCorpus) / sizeof(kIntegrationCorpus[0]); i++) {
        RoboTextShapeResult *result = IntegrationShape(&face, kIntegrationCorpus[i].text);
        const RoboTextMeasurement *measurement = RoboTextShapeResultMeasurement(result);
        RoboTextMeasurement again;
        RoboTextGlyphStats stats;

        RoboCheck(measurement != NULL);
        ConfExpectFloatClose(measurement->width, ConfTotalAdvance(result),
                             "text.shaping.integration.measurement_agrees", kIntegrationCorpus[i].label);
        RoboCheckEqInt((int)RoboTextShapeResultMeasure(result, NULL, &again, NULL), (int)RoboOk);
        ConfExpectFloatClose(again.width, measurement->width,
                             "text.shaping.integration.measurement_agrees", kIntegrationCorpus[i].label);
        /* The counters are a *sum over runs*, so a `glyphs` that disagrees with the measurement is a result
         * that contradicts itself. */
        RoboCheckEqInt((int)RoboTextShapeResultGetGlyphStats(result, &stats), (int)RoboOk);
        RoboCheckEqInt((int)stats.glyphs, (int)measurement->glyphCount);
        RoboCheckEqInt((int)stats.glyphRuns, (int)measurement->glyphRunCount);
        RoboCheckEqInt((int)stats.missing, (int)measurement->missingGlyphs);
        ConfExpectValid(result, "text.shaping.integration.measurement_agrees");
        RoboTextShapeResultDestroy(result);
    }
    ConfFaceClose(&face);
}

/* ------------------------------------------------------------------ */
/* §38 — clusters survive a second measurement                          */
/* ------------------------------------------------------------------ */

/** Clusters tile the source and the glyphs, and a re-measure (with ink) does not renumber them. */
static void TestShapingClustersSurvive(void)
{
    ConfFontSpec spec;
    ConfFace face;

    ConfSpecEuropean(&spec);
    ConfFaceOpen(&face, &spec, IntegrationSizePx);
    for (size_t i = 0u; i < sizeof(kIntegrationCorpus) / sizeof(kIntegrationCorpus[0]); i++) {
        RoboTextShapeResult *result = IntegrationShape(&face, kIntegrationCorpus[i].text);

        for (size_t run = 0u; run < RoboTextShapeResultGlyphRunCount(result); run++) {
            const RoboTextGlyphRun *glyphRun = RoboTextShapeResultGlyphRun(result, run);
            RoboTextRange source = RoboTextGlyphRunSourceRange(glyphRun);
            RoboTextScalarIndex at = source.start;
            RoboTextGlyphIndex glyphAt = 0u;

            /* The clusters tile both index spaces: no gap, no overlap, no empty cluster. */
            for (size_t c = 0u; c < RoboTextGlyphRunClusterCount(glyphRun); c++) {
                const RoboTextGlyphCluster *cluster =
                    RoboTextGlyphRunCluster(glyphRun, (RoboTextClusterIndex)c);

                RoboCheck(cluster != NULL);
                RoboCheckEqInt((int)cluster->source.start, (int)at);
                RoboCheck(cluster->source.end > cluster->source.start);
                RoboCheckEqInt((int)cluster->glyphStart, (int)glyphAt);
                RoboCheck(cluster->glyphEnd > cluster->glyphStart);
                at = cluster->source.end;
                glyphAt = cluster->glyphEnd;
            }
            RoboCheckEqInt((int)at, (int)source.end);
            RoboCheckEqInt((int)glyphAt, (int)RoboTextGlyphRunCount(glyphRun));
        }
        /* A re-measure that asks for ink bounds is a *different request*, and it must leave the runs
         * untouched — nothing between shaping and paint may renumber a cluster. */
        {
            RoboTextMeasureRequest request;
            RoboTextMeasurement bounded;
            size_t clustersBefore = 0u;
            size_t glyphsBefore = ConfTotalGlyphs(result);

            /* The default request plus ink bounds: the geometry that costs per glyph, asked for on purpose
             * so the case covers the *expensive* second pass and not only the cheap one. */
            RoboTextMeasureRequestInit(&request);
            request.options = (RoboTextMeasureOptions)(request.options | RoboTextMeasureOptionInkBounds);
            RoboCheckEqInt((int)RoboTextShapeResultMeasure(result, &request, &bounded, NULL), (int)RoboOk);
            for (size_t run = 0u; run < RoboTextShapeResultGlyphRunCount(result); run++) {
                clustersBefore += RoboTextGlyphRunClusterCount(RoboTextShapeResultGlyphRun(result, run));
            }
            RoboCheckEqInt((int)ConfTotalGlyphs(result), (int)glyphsBefore);
            RoboCheckEqInt((int)bounded.glyphCount, (int)glyphsBefore);
            RoboCheck(clustersBefore > 0u);
            /* The advances are the same numbers, so the bounded measurement is additional rather than a
             * second opinion. */
            ConfExpectFloatClose(bounded.width, ConfTotalAdvance(result),
                                 "text.shaping.integration.clusters_survive", kIntegrationCorpus[i].label);
        }
        RoboTextShapeResultDestroy(result);
    }
    ConfFaceClose(&face);
}

/* ------------------------------------------------------------------ */
/* §39 — determinism                                                    */
/* ------------------------------------------------------------------ */

/** The whole corpus shapes identically twice, and again over a face rebuilt from the same spec. */
static void TestShapingIntegrationDeterminism(void)
{
    ConfFontSpec spec;
    ConfFace first;
    ConfFace second;
    size_t glyphs = 0u;

    ConfSpecEuropean(&spec);
    ConfFaceOpen(&first, &spec, IntegrationSizePx);
    ConfFaceOpen(&second, &spec, IntegrationSizePx);
    for (size_t i = 0u; i < sizeof(kIntegrationCorpus) / sizeof(kIntegrationCorpus[0]); i++) {
        RoboTextShapeResult *a = IntegrationShape(&first, kIntegrationCorpus[i].text);
        RoboTextShapeResult *b = IntegrationShape(&first, kIntegrationCorpus[i].text);
        RoboTextShapeResult *c = IntegrationShape(&second, kIntegrationCorpus[i].text);

        RoboCheckMsg(ConfResultsEqual(a, b), "the same text shaped differently on the same face");
        RoboCheckMsg(ConfResultsEqual(a, c), "the same text shaped differently on a rebuilt face");
        ConfExpectValid(a, "text.shaping.integration.determinism");
        glyphs += ConfTotalGlyphs(a);
        RoboTextShapeResultDestroy(a);
        RoboTextShapeResultDestroy(b);
        RoboTextShapeResultDestroy(c);
    }
    /* A corpus that shaped nothing would pass every comparison above, so the count is asserted too. */
    RoboCheck(glyphs > 100u);
    ConfFaceClose(&second);
    ConfFaceClose(&first);
}

